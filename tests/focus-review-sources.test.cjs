'use strict';
const assert = require('node:assert/strict');
const { boot, seed } = require('./helpers/pocket-learning-ui.cjs');
const state = seed(2), clock = { now: new Date(2026, 9, 21, 9).getTime() };
state.materials.forEach(material => { material.title = '同名资料'; material.groups[0].start = 1; material.groups[0].end = 20; });
state.materials[0].videoLinks = [{ title: '讲义 PDF', url: 'https://example.test/a.pdf#page=12' }];
state.materials[1].videoLinks = [{ title: '资料 B', url: 'https://example.test/b.pdf#page=3' }];
const key = 'pocket-development-v1:cognivex-pocket-state';
const app = boot({ store: new Map([[key, JSON.stringify(state)]]), clock, location: new URL('http://localhost:4173/'), focusReview: true });
const model = app.context.PocketFocusReview, storage = app.context.PocketStorage;
let updated = storage.updateState(app.state(), next => {
  model.add(next, 'm1', 0, '3、7'); model.add(next, 'm2', 0, '3');
});
const questions = updated.focusReview.questions;
assert.equal(questions.length, 3);
assert.equal(questions[0].groupId, 'g1'); assert.equal(questions[2].groupId, 'g2');
assert.ok(questions[0].subjectId); assert.equal(questions[0].subjectId, questions[2].subjectId);
assert.notEqual(questions[0].id, questions[2].id);
assert.equal(JSON.stringify(updated.materials), JSON.stringify(app.state().materials));
const walk = node => [node, ...node.children.flatMap(walk)];
function reopen(next) {
  const result = boot({ store: new Map([[key, JSON.stringify(next)]]), clock, location: new URL('http://localhost:4173/'), focusReview: true });
  result.context.PocketFocusReviewUI.open({ subject: '数学', questionList: true }); return result;
}
let current = reopen(updated);
let page = current.document.getElementById('focus-review');
let rows = walk(page).filter(node => node.className === 'focus-question focus-strip');
assert.equal(rows.length, 2);
const text = node => walk(node).map(item => item.textContent).join('\n');
assert.match(text(rows[0]), /数学 · 同名资料/); assert.match(text(rows[0]), /第 3、7 题/);
assert.match(text(rows[1]), /第 3 题/); assert.ok(!text(page).includes('资料 ID'));
current.context.PocketFocusReviewUI.open({ subject: '数学' });
page = current.document.getElementById('focus-review');
assert.match(text(page), /每组题数/); assert.equal(model.groupingPlan(current.state(), '数学').questions.length, 3); assert.ok(!text(page).includes('资料 ID'));
const previewIds = model.available(updated, '数学').map(question => question.id);
const groupId = model.create(updated, '数学', 3, previewIds);
updated.materials[0].title = '最新资料名称';
const beforeDisplay = JSON.stringify(updated);
current = reopen(updated); current.context.PocketFocusReviewUI.open({ subject: '数学' });
page = current.document.getElementById('focus-review');
const groupRows = walk(page).filter(node => node.className === 'focus-group-row');
assert.equal(groupRows.length, 1);
assert.equal(groupRows[0].children[0].textContent, '最新资料名称、同名资料');
assert.ok(!walk(page).some(node => node.tag === 'h1' && node.textContent === '重点复习系统'));
assert.ok(walk(page).some(node => node.tag === 'h2' && node.textContent === '数学'));
assert.equal(JSON.stringify(current.state()), beforeDisplay, 'group names must be read-only and preserve member order');
current = reopen(updated); current.context.PocketFocusReviewUI.open({ subject: '数学', focusGroup: groupId });
page = current.document.getElementById('focus-review');
assert.match(text(page), /数学 · 最新资料名称/); assert.match(text(page), /数学 · 同名资料/);
assert.equal(JSON.stringify(current.state()), beforeDisplay, 'source display cannot migrate or rewrite records');
const snapshot = JSON.stringify(updated.focusReview.groups[0].members);
model.start(updated, groupId, clock.now);
current = reopen(updated); current.context.PocketFocusReviewUI.open({ subject: '数学', focusGroup: groupId });
page = current.document.getElementById('focus-review');
walk(page).find(node => node.tag === 'button' && node.textContent === '视频').fire('click');
assert.ok(walk(page).some(node => node.tag === 'a' && node.href === 'https://example.test/a.pdf#page=12'));
updated.materials.splice(0, 1);
current = reopen(updated); current.context.PocketFocusReviewUI.open({ subject: '数学', focusGroup: groupId });
page = current.document.getElementById('focus-review');
rows = walk(page).filter(node => node.className === 'focus-question focus-strip');
assert.match(text(rows[0]), /数学 · 同名资料/);
assert.equal(current.state().focusReview.groups[0].runs[0].questionIndex, 2);
assert.ok(!text(page).includes('部分题目来源不可用'));
assert.ok(!walk(rows[0]).some(node => node.className === 'field-error'));
assert.ok(!walk(page).some(node => node.tag === 'a' && node.href === 'https://example.test/a.pdf#page=12'), 'never fall back to an unavailable source or archived URL');
assert.ok(!walk(rows[0]).some(node => node.tag === 'button' && /查看原资料/.test(node.textContent)));
assert.equal(JSON.stringify(updated.focusReview.groups[0].members), snapshot);
const duplicate = JSON.parse(JSON.stringify(updated)); duplicate.materials.push(JSON.parse(JSON.stringify(duplicate.materials[0])));
assert.equal(model.locate(duplicate, questions[2]), null, 'duplicate material IDs are ambiguous and must not resolve');
const legacy = JSON.parse(JSON.stringify(updated));
delete legacy.focusReview.subjectRefs;
legacy.focusReview.questions.forEach(question => { delete question.subjectId; delete question.groupId; });
current = reopen(legacy); assert.match(text(current.document.getElementById('focus-review')), /第 3 题/);
assert.equal(current.state().focusReview.subjectRefs, undefined, 'old source display is read-only');
console.log('PASS localhost source rendering: subject/material/group/question, same-name isolation, mixed-group snapshots, live rename, exact PDF page URL, missing/ambiguous source denial and read-only legacy compatibility.');
