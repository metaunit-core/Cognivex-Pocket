'use strict';
const assert = require('node:assert/strict');
const { boot, seed } = require('./helpers/pocket-learning-ui.cjs');
const key = 'pocket-development-v1:cognivex-pocket-state';
const location = new URL('http://localhost:4173/');
const initial = seed(2);
initial.materials.forEach(material => { material.subject = '物理'; material.title = '受力分析'; material.groups[0].start = 1; material.groups[0].end = 20; });
let app = boot({ store: new Map([[key, JSON.stringify(initial)]]), location, focusReview: true });
const originalMaterials = JSON.stringify(app.state().materials), storage = app.context.PocketStorage, model = app.context.PocketFocusReview;
let state = storage.updateState(app.state(), next => { model.add(next, 'm1', 0, '3'); model.add(next, 'm2', 0, '3'); });
assert.equal(JSON.stringify(state.materials), originalMaterials);
assert.equal(state.focusReview.questions[0].subjectName, '物理');
assert.equal(state.focusReview.questions[0].materialTitle, '受力分析');
const groupId = model.create(state, '物理', 2, model.available(state, '物理').map(question => question.id));
model.start(state, groupId);
state = storage.updateState(storage.loadState(), next => { next.focusReview = state.focusReview; });
state = storage.updateMaterialMetadata(state, 'm1', 'subject', '力学');
state = storage.updateMaterialMetadata(state, 'm1', 'title', '受力分析修订版');
const renamedSource = JSON.stringify(state.materials);
state.focusReview.questions.forEach(question => { question.subjectName = '错误快照学科'; question.materialTitle = '错误快照资料'; });
state.focusReview.groups[0].members.forEach(question => { question.subjectName = '错误快照学科'; question.materialTitle = '错误快照资料'; });
state.focusReview.groups[0].runs[0].members.forEach(question => { question.subjectName = '错误快照学科'; question.materialTitle = '错误快照资料'; });
const beforeDisplay = JSON.stringify(state);
app = boot({ store: new Map([[key, beforeDisplay]]), location, focusReview: true });
const walk = node => [node, ...node.children.flatMap(walk)];
const text = () => walk(app.document.getElementById('focus-review')).map(node => node.textContent).join('\n');
for (const view of [{ subject: '物理', questionList: true }, { subject: '物理' }, { subject: '物理', focusGroup: groupId }]) {
  app.context.PocketFocusReviewUI.open(view);
  if (view.questionList || view.focusGroup) {
    assert.match(text(), /力学 · 受力分析修订版/);
    if (!view.focusGroup) assert.match(text(), /物理 · 受力分析/);
    assert.match(text(), /第 3 题/);
  } else assert.match(text(), /力学/);
  assert.ok(!text().includes('错误快照学科')); assert.ok(!text().includes('错误快照资料'));
}
assert.equal(JSON.stringify(app.state()), beforeDisplay, 'rendering must not rename sources, regroup or rewrite snapshots');
assert.equal(JSON.stringify(app.state().materials), renamedSource);
assert.equal(app.state().focusReview.session.runId, state.focusReview.session.runId);
const pendingState = JSON.parse(beforeDisplay);
pendingState.focusReview.groups = []; pendingState.focusReview.session = null;
app = boot({ store: new Map([[key, JSON.stringify(pendingState)]]), location, focusReview: true });
app.context.PocketFocusReviewUI.open({ subject: '物理' });
assert.match(text(), /每组题数/); assert.match(text(), /力学/); assert.equal(model.ordered(pendingState, '物理').length, 2);
const invalid = JSON.parse(beforeDisplay); delete invalid.materials[0].subject; delete invalid.materials[0].title;
const names = model.names(invalid, invalid.focusReview.questions[0]);
assert.equal(names.subject, '原学科字段缺失'); assert.equal(names.title, '原资料名称字段缺失');
assert.throws(() => model.add(invalid, 'm1', 0, '7'), /字段缺失/);
invalid.materials.shift();
assert.equal(model.names(invalid, invalid.focusReview.questions[0]).title, '来源不可用');
console.log('PASS localhost original subject/title reads, source-ID isolation, actual metadata-edit rename, stale-snapshot rejection across library/pending/group/training, missing-field errors and no source/schedule/admission mutation.');
