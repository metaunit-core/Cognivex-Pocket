'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { boot } = require('./helpers/pocket-learning-ui.cjs');
const read = name => fs.readFileSync(path.join(__dirname, '../js/' + name + '.js'), 'utf8');
const nodes = Object.fromEntries(['local-capacity-result', 'local-capacity-time', 'local-capacity-detail', 'local-capacity-warning', 'storage-cleanup-guide-entry', 'local-capacity-refresh'].map(id => [id, {
  textContent: '', hidden: false, disabled: false, className: '', events: {}, addEventListener(name, fn) { this.events[name] = fn; }
}]));
let bytes = 1014, failed = false, reads = 0;
const monitor = vm.createContext({ document: { getElementById: id => nodes[id] },
  PocketDeviceLocalData: { usage() { reads++; if (failed) throw Error('Denied'); return bytes; } }, Date });
vm.runInContext(read('local-capacity'), monitor);
assert.equal(nodes['local-capacity-result'].textContent, '0.99 KB / 5 MiB（参考）　正常');
assert.equal(nodes['local-capacity-detail'].textContent, '已使用 0.02% · 当前浏览器本地数据（估算）');
assert.equal(nodes['local-capacity-warning'].hidden, true);
assert.equal(nodes['storage-cleanup-guide-entry'].disabled, false);
for (const [fraction, status] of [[0, '正常'], [0.699, '正常'], [0.7, '注意容量'], [0.899, '注意容量'], [0.9, '接近参考上限'], [1.2, '接近参考上限']]) {
  bytes = 5 * 1024 * 1024 * fraction;
  nodes['local-capacity-refresh'].events.click();
  assert.ok(nodes['local-capacity-result'].textContent.endsWith(status));
  assert.equal(nodes['local-capacity-warning'].hidden, fraction < 0.7);
  assert.equal(nodes['storage-cleanup-guide-entry'].className.includes('local-capacity-guide-warning'), fraction >= 0.7);
  assert.ok(nodes['local-capacity-detail'].textContent.includes((fraction * 100).toFixed(2) + '%'));
}
assert.match(nodes['local-capacity-result'].textContent, /MB/);
failed = true; monitor.PocketLocalCapacity.refresh();
assert.equal(nodes['local-capacity-result'].textContent, '检测失败');
assert.equal(nodes['local-capacity-warning'].hidden, true);
assert.equal(nodes['storage-cleanup-guide-entry'].className, 'secondary');
assert.ok(reads > 0);
const html = fs.readFileSync(path.join(__dirname, '../index.html'), 'utf8');
assert.ok(html.includes('刷新检测'));
assert.ok(html.includes('5 MiB 为参考值，非浏览器实测存储上限。'));
assert.ok(!html.includes('按键和值的 UTF-16 长度估算占用'));
assert.match(fs.readFileSync(path.join(__dirname, '../css/style.css'), 'utf8'), /#local-capacity \.local-capacity-actions \{ display: flex; flex-wrap: wrap;/);
const app = boot();
const guide = read('storage-cleanup-guide');
vm.runInContext(guide, app.context);
app.context.PocketLearning.showHome();
const before = app.store.get('cognivex-pocket-state');
app.nodes['learned-material-details'].open = true;
app.nodes['pocket-settings'].open = true;
app.context.scrollY = 470;
app.nodes['storage-cleanup-guide-entry'].fire('click');
const page = app.document.getElementById('storage-cleanup-guide');
assert.equal(page.hidden, false);
assert.equal(app.nodes['pocket-main'].hidden, true);
const walk = node => [node, ...node.children.flatMap(walk)];
const content = walk(page).map(node => node.textContent).join(' ');
for (const text of ['本地数据空间清理流程', '空间清理指引', '① 导出学习档案备份', '② 清空本设备本地数据', '③ 删除 Firebase 所有内容', '④ 查看删除功能指导', '⑤ 重新开始 Firebase 备份', '返回 Pocket →「② 备份与导出」→「删除功能指导」，按照现有指导完成相关操作。']) assert.ok(content.includes(text));
assert.equal(page.children.filter(node => node.tag === 'section').length, 5);
assert.equal(walk(page).filter(node => node.tag === 'button').length, 1);
assert.equal(walk(page).filter(node => ['input', 'textarea', 'select'].includes(node.tag)).length, 0);
page.children[0].fire('click');
assert.equal(page.hidden, true);
assert.equal(app.nodes['pocket-main'].hidden, false);
assert.equal(app.nodes['learned-material-details'].open, true);
assert.equal(app.nodes['pocket-settings'].open, true);
assert.equal(app.context.scrollY, 470);
assert.equal(app.store.get('cognivex-pocket-state'), before);
app.nodes['storage-cleanup-guide-entry'].fire('click');
app.fire('pagehide');
const reopened = boot({ store: app.store });
vm.runInContext(guide, reopened.context); reopened.context.PocketNavigation.restore();
assert.equal(reopened.document.getElementById('storage-cleanup-guide').hidden, false);
reopened.nodes['pocket-back-button'].fire('click');
assert.equal(reopened.nodes['pocket-settings'].open, true);
assert.equal(reopened.context.scrollY, 470);
reopened.nodes['storage-cleanup-guide-entry'].fire('click');
reopened.nodes['pocket-home-button'].fire('click');
assert.equal(reopened.document.getElementById('storage-cleanup-guide').hidden, true);
console.log('PASS: dynamic compact capacity, unchanged 70/90 thresholds, warning/error reset, manual refresh, wrapped actions, five read-only guide steps, return/scroll/expansion/reload/home and unchanged learning data.');
