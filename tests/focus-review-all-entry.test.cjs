'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const { boot, seed } = require('./helpers/pocket-learning-ui.cjs');
const location = new URL('http://localhost:4173/'), key = 'pocket-development-v1:cognivex-pocket-state';
const state = seed(1); state.materials[0].groups[0].start = 1; state.materials[0].groups[0].end = 20;
let app = boot({ location, focusReview: true });
const model = app.context.PocketFocusReview;
model.add(state, 'm1', 0, '1、2、3');
const groupId = model.create(state, '数学', 3, model.available(state, '数学').map(question => question.id));
model.start(state, groupId);
const singleRun = model.active(state).run.id;
model.transition(state, singleRun, 'finish', {}, Date.now(), 0);
const singleGroups = JSON.stringify(state.focusReview.groups), singleSession = JSON.stringify(state.focusReview.session);
app = boot({ location, store: new Map([[key, JSON.stringify(state)]]), focusReview: true });
const walk = node => [node, ...node.children.flatMap(walk)];
const page = () => app.document.getElementById('focus-review');
const press = label => { const node = walk(page()).find(node => node.tag === 'button' && node.textContent === label); assert.ok(node, label); assert.equal(node.disabled, false); node.fire('click'); };
const open = () => app.context.PocketFocusReviewUI.open({ subject: '数学' });
open();
assert.equal(app.document.getElementById('focus-group-size').value, '');
app.document.getElementById('focus-filter-accuracy-mode').value = 'limit';
app.document.getElementById('focus-filter-accuracy-mode').fire('change');
assert.ok(walk(page()).some(node => node.textContent.includes('正确率请输入')));
assert.equal(app.context.PocketReviewAdmission.status(app.state()).dailyCompleted, false);
const beforeFailed = app.store.get(key); app.fail.enabled = true; press('全部复习'); assert.equal(app.store.get(key), beforeFailed);
app.fail.enabled = false; press('全部复习');
assert.equal(JSON.stringify(app.state().focusReview.groups), singleGroups);
assert.equal(JSON.stringify(app.state().focusReview.pausedSessions[0]), singleSession);
const firstAllId = app.state().focusReview.session.groupId;
assert.notEqual(firstAllId, groupId);
assert.deepEqual(JSON.parse(JSON.stringify(app.context.PocketFocusReview.active(app.state()).run.members.map(question => question.number))), [1, 2, 3]);
press('输出达标 → 下一步');
open(); press('全部复习'); assert.equal(app.context.PocketFocusReview.active(app.state()).index, 1);
app = boot({ location, store: app.store, focusReview: true }); open(); press('全部复习');
assert.equal(app.context.PocketFocusReview.active(app.state()).index, 1);
press('输出达标 → 下一步'); press('输出达标 → 下一步');
assert.equal(app.state().focusReview.session, null);
assert.equal(app.context.PocketReviewAdmission.status(app.state()).focusCompleted, true);
open(); press('全部复习');
assert.equal(app.state().focusReview.allReviews.length, 2);
assert.equal(app.context.PocketFocusReview.active(app.state()).index, 0);
assert.equal(JSON.stringify(app.state().focusReview.groups.map(group => ({ ...group, runs: group.runs.slice(0, 1) }))), singleGroups);
for (let index = 0; index < 3; index++) press('输出达标 → 下一步');
open(); press('复习');
assert.equal(app.context.PocketFocusReview.active(app.state()).run.id, singleRun);
assert.equal(app.context.PocketFocusReview.active(app.state()).index, 1);
assert.equal(app.state().focusReview.groups[0].runs.length, 3);
for (let index = 1; index < 3; index++) press('输出达标 → 下一步');
const zero = app.state();
zero.focusReview.questions.forEach(question => { question.status = 'mastered'; });
const beforeZero = JSON.stringify(zero);
assert.throws(() => model.startAll(zero, '数学'), /暂无已分组的重点题/);
assert.equal(JSON.stringify(zero), beforeZero);
const noQuestions = boot({ location, store: new Map([[key, JSON.stringify(zero)]]), focusReview: true });
noQuestions.context.PocketFocusReviewUI.open({ subject: '数学' });
const noQuestionsPage = noQuestions.document.getElementById('focus-review');
assert.ok(walk(noQuestionsPage).some(node => node.textContent === '暂无已分组的重点题'));
assert.equal(walk(noQuestionsPage).find(node => node.tag === 'button' && node.textContent === '全部复习').disabled, true);
const switching = seed(2);
switching.materials.forEach(material => { material.groups[0].start = 1; material.groups[0].end = 20; });
switching.materials[1].subject = '物理';
model.add(switching, 'm1', 0, '1'); model.add(switching, 'm2', 0, '2');
const mathId = model.create(switching, '数学', 1, model.available(switching, '数学').map(question => question.id));
model.create(switching, '物理', 1, model.available(switching, '物理').map(question => question.id));
model.start(switching, mathId); switching.focusReview.session.step = 'video';
const videoSession = JSON.stringify(switching.focusReview.session);
const mathAll = model.startAll(switching, '数学');
const physicsAll = model.startAll(switching, '物理');
assert.notEqual(mathAll, physicsAll);
assert.equal(model.startAll(switching, '数学'), mathAll);
assert.equal(switching.focusReview.allReviews.length, 2);
model.transition(switching, model.active(switching).run.id, 'finish', {}, Date.now(), 0);
model.start(switching, mathId);
assert.equal(JSON.stringify(switching.focusReview.session), videoSession);
assert.equal(switching.focusReview.pausedSessions.length, 1);
const scores = app.state();
for (const group of [...scores.focusReview.groups, ...scores.focusReview.allReviews]) for (const run of group.runs) {
  run.accuracy = '10/10'; run.questionProgress.forEach(record => { record.accuracy = '10/10'; });
}
app = boot({ location, store: new Map([[key, JSON.stringify(scores)]]), focusReview: true }); open();
app.document.getElementById('focus-filter-accuracy-mode').value = 'limit';
app.document.getElementById('focus-filter-accuracy').value = '0';
app.document.getElementById('focus-filter-accuracy-mode').fire('change');
assert.ok(walk(page()).some(node => node.textContent.includes('筛选结果：0道')));
press('全部复习');
assert.equal(app.context.PocketFocusReview.active(app.state()).run.members.length, 3);
vm.runInContext(fs.readFileSync(path.join(__dirname, '../js/learning-backup.js'), 'utf8'), app.context);
console.log('PASS grouped-only availability, invalid/zero filters and empty size isolation, pause/resume single checkpoint, save failure, reload, repeat all rounds and no empty launch.');
(async () => {
  const backup = await app.context.PocketLearningBackup.create();
  assert.equal((await app.context.PocketLearningBackup.verify(JSON.stringify(backup))).valid, true);
})().catch(error => { console.error(error); process.exitCode = 1; });
