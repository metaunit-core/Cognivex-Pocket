'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const { boot, seed } = require('./helpers/pocket-learning-ui.cjs');
const location = new URL('http://localhost:4173/'), key = 'pocket-development-v1:cognivex-pocket-state';
const initial = seed(3); initial.materials[1].title = initial.materials[0].title;
require('./helpers/original-learning-fixture.cjs')(initial, new Date(2026,9,18,9).getTime());
initial.materials.forEach(m => { m.groups[0].start = 1; m.groups[0].end = 20; });
const setup = boot({ location, focusReview: true }), model = setup.context.PocketFocusReview;
model.add(initial, 'm1', 0, '1、2'); model.add(initial, 'm2', 0, '3、4');
const mixed = model.create(initial, '数学', 4, model.available(initial, '数学').map(q => q.id));
model.start(initial, mixed);
while (model.active(initial)) model.transition(initial, model.active(initial).run.id, 'finish', { accuracy: '2/4', durationMinutes: '8' });
const history = JSON.stringify(initial.focusReview.groups[0].runs);
model.startAll(initial, '数学');
setup.context.PocketDailyReverse.start(initial);
setup.context.PocketMaterialReview.start(initial);
const retained = JSON.stringify(initial.materials.slice(1));
let app = boot({ location, store: new Map([[key, JSON.stringify(initial)]]), focusReview: true });
const walk = n => [n, ...n.children.flatMap(walk)];
const dialog = () => app.document.getElementById('materials-dialog');
const click = (label, parent = dialog()) => { const n = walk(parent).find(n => n.tag === 'button' && n.textContent === label); assert.ok(n, label); n.fire('click'); return n; };
const open = () => app.document.getElementById('learned-material-details').fire('click');
const select = id => { const n = walk(dialog()).find(n => n['data-material-id'] === id); assert.ok(n); n.checked = true; n.fire('change'); };
const stateBytes = () => app.store.get(key);
assert.equal(app.document.getElementById('learned-material-details').tag, 'button');
assert.equal(dialog().hidden, true); open();
assert.equal(dialog().hidden, false);
assert.equal(walk(dialog()).filter(n => n.type === 'checkbox').length, 3);
assert.ok(walk(dialog()).filter(n => n.type === 'checkbox').every(n => !n.checked));
assert.equal(app.document.getElementById('delete-selected-materials').disabled, true);
const before = stateBytes(); select('m1'); assert.equal(stateBytes(), before);
click('删除选中资料（1）'); assert.equal(stateBytes(), before);
const cancelledConfirm = app.document.getElementById('confirm-delete-materials');
assert.match(walk(dialog()).map(n => n.textContent).join('\n'), /这些资料对应的本地学习数据将被删除。/);
click('取消'); assert.equal(stateBytes(), before); cancelledConfirm.fire('click'); assert.equal(stateBytes(), before);
click('删除选中资料（1）'); const confirm = click('确认删除'); confirm.fire('click');
const saved = app.state();
assert.deepEqual(saved.materials.map(m => m.id), ['m2', 'm3'], app.document.getElementById('materials-dialog-status').textContent);
assert.equal(JSON.stringify(saved.materials), retained);
assert.equal(saved.focusReview.questions.length, 2);
assert.equal(JSON.stringify(saved.focusReview.groups[0].runs.slice(0, 1)), history);
assert.equal(saved.focusReview.groups[0].members.length, 4, 'shared historical member snapshots retained');
assert.equal(model.active(saved).question.materialId, 'm2');
assert.equal(setup.context.PocketDailyReverse.validRound(saved.dailyReverseReview.round), true);
assert.deepEqual(saved.dailyReverseReview.round.ids, ['m2', 'm3']);
assert.ok(saved.dailyReverseReview.round.tasks.every(t => t.materialId !== 'm1'));
assert.ok(saved.materialReviewSession.queue.every(t => t.materialId !== 'm1'));
assert.match(app.document.getElementById('materials-dialog-status').textContent, /已删除 1 条/);
assert.equal(saved.materials[0].title, initial.materials[0].title, 'same-name unselected material remains');
app = boot({ location, store: app.store, focusReview: true }); assert.equal(app.state().materials.length, 2); open();
// Existing detail and metadata editor remain accessible from the modal.
const detail = walk(app.document.getElementById('material-list-items')).find(n => n.tag === 'button'); detail.fire('click');
assert.equal(dialog().hidden, true); assert.equal(app.nodes['learning-heading'].textContent, '资料详情');
assert.ok(app.content().some(n => n.textContent === '更改资料'));
app.button('更改资料').fire('click'); assert.ok(app.document.getElementById('edit-material-title'));
// Local storage failure is atomic and cannot claim success.
app.context.PocketLearning.showHome(); open(); select('m2'); click('删除选中资料（1）');
const failureBytes = stateBytes(); app.fail.enabled = true; click('确认删除'); app.fail.enabled = false;
assert.equal(stateBytes(), failureBytes); assert.match(app.document.getElementById('materials-dialog-status').textContent, /删除未完成/);
const concurrent = JSON.parse(failureBytes); concurrent.materials[0].title = 'other-window-change';
app.store.set(key, JSON.stringify(concurrent)); click('确认删除');
assert.equal(app.store.get(key), JSON.stringify(concurrent));
assert.match(app.document.getElementById('materials-dialog-status').textContent, /其他窗口/);
app.store.set(key, failureBytes);
click('取消'); click('关闭'); open(); select('m2'); select('m3'); click('删除选中资料（2）'); click('确认删除');
assert.equal(app.state().materials.length, 0);
assert.equal(app.state().materialReviewSession, null); assert.equal(app.state().dailyReverseReview.round, undefined);
assert.equal(model.active(app.state()), null);
assert.match(walk(dialog()).map(n => n.textContent).join('\n'), /暂无学习资料/);
// Restore earlier saved snapshot for latest-state archive/JSON verification.
app = boot({ location, store: new Map([[key, JSON.stringify(saved)]]), focusReview: true });
for (const name of ['learning-backup', 'learning-archive']) vm.runInContext(fs.readFileSync(path.join(__dirname, '../js/' + name + '.js'), 'utf8'), app.context);
const archive = app.context.PocketLearningArchive.render(stateBytes());
assert.doesNotMatch(archive.split('## 二、')[0], /资料3.*资料3/);
const focusCurrent = archive.split('## 二、')[1].split('### 已熟练')[0];
assert.doesNotMatch(focusCurrent, /第1、2题/); assert.match(focusCurrent, /第3、4题/);
const stale = JSON.parse(JSON.stringify(initial));
assert.throws(() => app.context.PocketStorage.updateState(stale, next => { next.materials[0].title = 'resurrect'; }), /其他窗口/);
const clone = x => JSON.parse(JSON.stringify(x));
const current = seed(2); current.currentSession = { currentStep: 'output', materialId: 'm1' };
app.context.PocketMaterialDeletion.remove(current, ['m1']); assert.equal(current.currentSession, null);
assert.throws(() => app.context.PocketMaterialDeletion.remove(clone(saved), ['missing']), /列表已变化/);
const duplicate = clone(saved); duplicate.materials.push(clone(duplicate.materials[0]));
assert.throws(() => app.context.PocketMaterialDeletion.remove(duplicate, ['m2']), /ID 不唯一/);
// Removing an active reverse-review material activates the next survivor in its original order.
const reverse = require('./helpers/original-learning-fixture.cjs')(seed(3), new Date(2026,9,18,9).getTime()); setup.context.PocketMaterialReview.start(reverse);
assert.equal(reverse.materialReviewSession.materialId, 'm3');
app.context.PocketMaterialDeletion.remove(reverse, ['m3']);
assert.equal(reverse.materialReviewSession.materialId, 'm2');
assert.deepEqual(Array.from(reverse.materialReviewSession.queue, t => t.materialId), ['m2', 'm1']);
assert.equal(setup.context.PocketMaterialReview.needsInitialization(reverse), false);
// A completion remains a real completion; trimming completed tasks does not reorder or reset other work.
const dailyProgress = seed(3); setup.context.PocketDailyReverse.start(dailyProgress);
let round = dailyProgress.dailyReverseReview.round, task = setup.context.PocketDailyReverse.task(dailyProgress);
setup.context.PocketDailyReverse.transition(dailyProgress, 'outputDone', { roundId: round.id, index: round.index, materialId: 'm1', taskIndex: round.taskIndex, currentGroupIndex: task.groupIndex });
const completed = JSON.stringify(dailyProgress.dailyReverseReview.round.tasks[0]);
app.context.PocketMaterialDeletion.remove(dailyProgress, ['m2']);
round = dailyProgress.dailyReverseReview.round;
assert.equal(setup.context.PocketDailyReverse.validRound(round), true); assert.equal(round.index, 1);
assert.equal(JSON.stringify(round.tasks[0]), completed); assert.equal(setup.context.PocketDailyReverse.current(dailyProgress).id, 'm3');
// Stale grants cannot become valid; newly appended/unreviewed Groups do not join an existing reverse queue.
const grant = seed(2); grant.review.unlock = { collectionKey: 'stale', generation: 0, usedAt: null };
app.context.PocketMaterialDeletion.remove(grant, ['m1']); assert.equal(grant.review.unlock, undefined);
// Paused single-Group and active all-review sessions both resume a surviving question.
const paused = clone(initial); paused.focusReview.session = null; paused.focusReview.pausedSessions = [];
model.start(paused, mixed); model.startAll(paused, '数学');
app.context.PocketMaterialDeletion.remove(paused, ['m1']);
assert.equal(model.active(paused).question.materialId, 'm2');
assert.equal(paused.focusReview.pausedSessions.length, 1);
const resumed = { ...paused, focusReview: { ...paused.focusReview, session: paused.focusReview.pausedSessions[0] } };
assert.equal(model.active(resumed).question.materialId, 'm2');
// Unknown legacy queue formats fail atomically through the regular storage transaction.
const legacy = seed(2); legacy.materialReviewSession = { materialIds: ['m1', 'm2'], materialId: 'm1', currentStep: 'output' };
const legacyStore = new Map([[key, JSON.stringify(legacy)]]), guarded = boot({ location, store: legacyStore, focusReview: true });
const guardedBytes = legacyStore.get(key);
assert.throws(() => guarded.context.PocketStorage.updateState(guarded.state(), next => guarded.context.PocketMaterialDeletion.remove(next, ['m1'])), /旧版倒序/);
assert.equal(legacyStore.get(key), guardedBytes);
module.exports = (async () => {
  const backup = await app.context.PocketLearningBackup.create();
  assert.equal((await app.context.PocketLearningBackup.verify(JSON.stringify(backup))).valid, true);
  assert.deepEqual(JSON.parse(backup.rawState).materials.map(m => m.id), ['m2', 'm3']);
  const restored = boot({ location, store: new Map([[key, backup.rawState]]), focusReview: true });
  assert.equal(JSON.stringify(restored.state().focusReview), JSON.stringify(saved.focusReview));
  console.log('PASS localhost material modal, independent IDs, confirmation/cancel, atomic failure, batch deletion, task/focus cleanup, exports, stale writer and JSON restore.');
})();
