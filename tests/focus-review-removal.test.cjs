'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const { boot, seed } = require('./helpers/pocket-learning-ui.cjs');
const key = 'pocket-development-v1:cognivex-pocket-state', location = new URL('http://localhost:4173/');
const probe = boot({ location, focusReview: true }), model = probe.context.PocketFocusReview;
function fixture() {
  const state = seed(1); state.materials[0].groups[0].start = 1; state.materials[0].groups[0].end = 20;
  model.add(state, 'm1', 0, '1、2、3', false, 100);
  model.create(state, '数学', 3, model.available(state, '数学').map(question => question.id), 101);
  return state;
}
const walk = node => [node, ...node.children.flatMap(walk)];
for (const mode of ['single', 'all']) {
  const initial = fixture(), materials = JSON.stringify(initial.materials);
  if (mode === 'all') model.startAll(initial, '数学'); else model.start(initial, initial.focusReview.groups[0].id);
  let app = boot({ store: new Map([[key, JSON.stringify(initial)]]), location, focusReview: true });
  const groupId = initial.focusReview.session.groupId;
  const open = () => app.context.PocketFocusReviewUI.open({ subject: '数学', focusGroup: groupId });
  const page = () => app.document.getElementById('focus-review');
  const press = label => { const node = walk(page()).find(node => node.tag === 'button' && node.textContent === label && !node.disabled); assert.ok(node, label); node.fire('click'); return node; };
  const selectCurrent = () => {
    const question = app.context.PocketFocusReview.active(app.state()).question;
    const label = walk(page()).find(node => node.className === 'focus-removal-choice' && node.children[1].textContent.endsWith('第 ' + question.number + ' 题'));
    label.children[0].checked = true; label.children[0].fire('change');
  };
  open();
  const removal = page().children.find(node => node.className === 'focus-question-removal');
  const next = page().children[page().children.indexOf(removal) + 1];
  assert.equal(next.tag, 'details'); assert.match(next.children[0].textContent, /复习记录/);
  const unchanged = app.store.get(key);
  press('移除'); press('取消'); assert.equal(app.store.get(key), unchanged);
  press('移除'); selectCurrent(); app.fail.enabled = true; press('确认移出所选题目'); assert.equal(app.store.get(key), unchanged);
  app.fail.enabled = false; const stale = press('确认移出所选题目'); stale.fire('click');
  assert.equal(app.context.PocketFocusReview.active(app.state()).index, 1);
  assert.equal(app.state().focusReview.questions[0].status, 'mastered');
  assert.equal(app.state().focusReview.questions[0].events.length, 2);
  assert.equal(app.context.PocketReviewAdmission.status(app.state()).focusCompleted, false);
  const firstRecord = app.context.PocketFocusReview.active(app.state()).run.questionProgress[0];
  assert.equal(firstRecord.outputCompleted, false); assert.equal(firstRecord.resolution, 'removed');
  app = boot({ store: app.store, location, focusReview: true }); open();
  assert.equal(app.context.PocketFocusReview.active(app.state()).index, 1);
  press('输出达标 → 下一步');
  assert.equal(app.context.PocketReviewAdmission.status(app.state()).focusCompleted, false);
  press('移除'); selectCurrent(); press('确认移出所选题目');
  assert.equal(app.state().focusReview.session, null);
  assert.equal(app.context.PocketReviewAdmission.status(app.state()).focusCompleted, true);
  assert.equal(JSON.stringify(app.state().materials), materials);
  const saved = app.state(), run = app.context.PocketFocusReview.findGroup(saved, groupId).runs[0];
  assert.equal(run.questionProgress.length, 3); assert.equal(run.questionProgress.filter(record => record.outputCompleted).length, 1);
  assert.equal(app.context.PocketFocusReview.groupingPlan(saved, '数学').questions.length, 1);
  const questionsBefore = saved.focusReview.questions.length, addedAt = saved.focusReview.questions[0].addedAt, history = JSON.stringify(run);
  model.add(saved, 'm1', 0, '1');
  assert.equal(saved.focusReview.questions.length, questionsBefore); assert.equal(saved.focusReview.questions[0].status, 'active');
  assert.equal(saved.focusReview.questions[0].addedAt, addedAt); assert.equal(JSON.stringify(run), history);
  vm.runInContext(fs.readFileSync(path.join(__dirname, '../js/learning-backup.js'), 'utf8'), app.context);
  vm.runInContext(fs.readFileSync(path.join(__dirname, '../js/learning-archive.js'), 'utf8'), app.context);
  const raw = app.store.get(key), markdown = app.context.PocketLearningArchive.render(raw);
  assert.match(markdown, /已熟练、已移出及来源不可用的重点题/); assert.match(markdown, /\| 已熟练 \|/);
  assert.equal(app.store.get(key), raw);
}
const onlyRemoved = fixture(); model.startAll(onlyRemoved, '数学');
const runId = model.active(onlyRemoved).run.id;
for (let index = 0; index < 3; index++) model.transition(onlyRemoved, runId, 'remove', {}, Date.now(), index);
assert.equal(onlyRemoved.focusReview.session, null);
assert.equal(onlyRemoved.focusReview.allReviews[0].runs[0].outputCompleted, false);
assert.equal(probe.context.PocketReviewAdmission.status(onlyRemoved).focusCompleted, false);
assert.equal(model.allQuestions(onlyRemoved, '数学').length, 0);
const inactive = fixture(); model.start(inactive, inactive.focusReview.groups[0].id);
model.setStatus(inactive, inactive.focusReview.questions[1].id, 'removed');
model.transition(inactive, model.active(inactive).run.id, 'remove', {}, Date.now(), 0);
assert.equal(model.active(inactive).index, 2); assert.equal(model.active(inactive).run.questionProgress[1].resolution, 'inactive');
const singleton = seed(1); model.add(singleton, 'm1', 0, String(singleton.materials[0].groups[0].start));
const singletonGroup = model.create(singleton, '数学', 1, [singleton.focusReview.questions[0].id]);
model.start(singleton, singletonGroup);
model.transition(singleton, model.active(singleton).run.id, 'remove', {}, Date.now(), 0);
assert.equal(singleton.focusReview.session, null);
assert.equal(singleton.focusReview.groups[0].runs[0].questionProgress[0].resolution, 'removed');
assert.equal(probe.context.PocketReviewAdmission.status(singleton).focusCompleted, false);
console.log('PASS single/all removal confirmation, cancellation/failure atomicity, stale clicks, next/resume/end, no fake OUTPUT/admission, source/history retention, rejoin, inactive skipping and archive.');
(async () => {
  const app = boot({ location, store: new Map([[key, JSON.stringify(onlyRemoved)]]), focusReview: true });
  let cloudCalls = 0;
  app.context.PocketCloudBackup = { upload() { cloudCalls++; throw Error('Unexpected cloud write'); }, delete() { cloudCalls++; throw Error('Unexpected cloud delete'); } };
  vm.runInContext(fs.readFileSync(path.join(__dirname, '../js/learning-backup.js'), 'utf8'), app.context);
  const before = app.store.get(key), backup = await app.context.PocketLearningBackup.create();
  assert.equal((await app.context.PocketLearningBackup.verify(JSON.stringify(backup))).valid, true);
  const restored = boot({ location, store: new Map([[key, backup.rawState]]), focusReview: true });
  assert.equal(JSON.stringify(restored.state().focusReview), JSON.stringify(onlyRemoved.focusReview));
  assert.equal(app.store.get(key), before); assert.equal(cloudCalls, 0);
})().catch(error => { console.error(error); process.exitCode = 1; });
