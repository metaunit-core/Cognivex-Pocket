'use strict';
const assert = require('node:assert/strict');
const { boot } = require('./helpers/pocket-learning-ui.cjs');
const location = new URL('http://localhost:4173/');
let app = boot({ location });
app.nodes['quick-material-entry'].fire('click');
const page = app.document.getElementById('quick-material');
const walk = n => [n, ...n.children.flatMap(walk)];
const form = walk(page).find(n => n.tag === 'form');
const save = walk(form).find(n => n.tag === 'button');
const input = key => app.document.getElementById('quick-material-' + key);
const fill = (key, value) => { input(key).value = value; input(key).fire('input'); };
fill('subject', '数学');
for (const title of ['函数', '导数2', '向量']) {
  fill('title', title); fill('questionRange', '1-5'); fill('groupSize', '2');
  const count = app.state().materials.length;
  form.fire('submit'); form.fire('submit');
  assert.equal(app.state().materials.length, count + 1);
  assert.equal(page.hidden, false); assert.equal(app.nodes['pocket-main'].hidden, true);
  assert.equal(input('subject').value, '数学');
  for (const key of ['title', 'questionRange', 'groupSize']) assert.equal(input(key).value, '');
  assert.equal(app.document.getElementById('quick-material-preview').children.length, 0);
  assert.equal(save.disabled, true);
  assert.equal(app.focus.at(-1), input('title'));
  assert.equal(app.document.getElementById('quick-material-status').textContent, '学习资料保存成功，可继续新增下一份。');
}
assert.deepEqual(app.state().materials.map(m => m.title), ['函数', '导数2', '向量']);
assert.equal(new Set(app.state().materials.map(m => m.id)).size, 3);
assert.ok(app.state().materials.every(m => m.status === 'completed'));
fill('subject', '物理'); fill('title', '重试资料'); fill('questionRange', '3-7,10'); fill('groupSize', '3');
app.fail.enabled = true; form.fire('submit'); app.fail.enabled = false;
assert.equal(app.state().materials.length, 3);
for (const [key, value] of Object.entries({ subject: '物理', title: '重试资料', questionRange: '3-7,10', groupSize: '3' })) assert.equal(input(key).value, value);
assert.ok(walk(form).some(n => n.textContent.startsWith('保存失败：')));
assert.equal(save.disabled, false);
form.fire('submit'); form.fire('submit'); assert.equal(app.state().materials.length, 4);
const before = JSON.stringify(app.state().materials);
app = boot({ location, store: app.store });
assert.equal(JSON.stringify(app.state().materials), before);
assert.equal(app.document.getElementById('quick-material').hidden, false);
console.log('PASS localhost continuous 3 saves, same page/form, retained subject, reset/defaults, focus, order, no duplicate submit, failed save retains all fields, retry and reload.');
