'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { local, remote, bind, initial } = require('./helpers/pocket-cloud-fixture.cjs');
(async () => {
  const cloud = remote(), device = local(cloud);
  await bind(device);
  const before = JSON.stringify([...device.store]);
  let handler, answer = null, confirm = false, reloads = 0;
  const node = { disabled: false, textContent: '', addEventListener: (_, fn) => { handler = fn; } };
  device.context.document = { getElementById: () => node };
  device.context.window = device.context;
  device.context.prompt = () => answer;
  device.context.confirm = () => confirm;
  device.context.location = { reload() { reloads++; } };
  device.context.showMessage = text => { node.textContent = text; };
  const app = fs.readFileSync(path.join(__dirname, '../js/app.js'), 'utf8');
  vm.runInContext(app.slice(app.indexOf("  document.getElementById('reset-data-button')?.addEventListener"), app.indexOf("  document.getElementById('start-review-button')")), device.context);
  await handler(); // cancelled prompt
  assert.equal(JSON.stringify([...device.store]), before);
  answer = 'clear'; confirm = true; await handler();
  assert.equal(JSON.stringify([...device.store]), before);
  answer = 'CLEAR'; confirm = false; await handler();
  assert.equal(JSON.stringify([...device.store]), before);
  assert.equal(reloads, 0);
  const remoteBefore = JSON.stringify({ heads: [...cloud.heads], manifests: [...cloud.manifests], chunks: [...cloud.chunks] });
  const other = local(cloud); await bind(other, 'B');
  const otherBefore = JSON.stringify([...other.store]);
  const allCloudBefore = JSON.stringify({ heads: [...cloud.heads], manifests: [...cloud.manifests], chunks: [...cloud.chunks] });
  device.store.set('unrelated-site-data', 'keep');
  device.store.set('pocket-cloud-emergency-old', 'local learning rescue');
  assert.equal(device.context.PocketDataDeletion.preview().counts.runs, 1);
  confirm = true; await handler();
  assert.equal(reloads, 1);
  for (const key of device.context.PocketCloudBackup.DATA_KEYS) assert.equal(device.store.has(key), false);
  assert.equal(device.store.has('pocket-cloud-emergency-old'), false);
  assert.equal(device.store.get('firebase:authUser:secret'), 'must never upload');
  assert.equal(device.store.get('unrelated-site-data'), 'keep');
  assert.equal(JSON.stringify([...other.store]), otherBefore);
  assert.equal(JSON.stringify({ heads: [...cloud.heads], manifests: [...cloud.manifests], chunks: [...cloud.chunks] }), allCloudBefore);
  await device.engine.retry(); await device.fire();
  assert.equal(cloud.stats.commits, 2);
  assert.match(device.engine.view().status, /本机学习数据已清空/);
  const reopened = local(cloud, null, device.store);
  reopened.context.PocketStorage.loadState();
  await reopened.engine.setUser({ uid: 'A' });
  await reopened.engine.retry(); await reopened.fire();
  assert.equal(JSON.parse(reopened.store.get('cognivex-pocket-state')).materials.length, 0);
  assert.equal(reopened.engine.view().localReset, true);
  assert.equal(cloud.stats.commits, 2);
  const comparison = await reopened.engine.compare();
  assert.equal(reopened.engine.view().localReset, true);
  await assert.rejects(reopened.engine.bindLocal(comparison, true), /等待手动删除/);
  // Manual cloud-deletion waiting forbids every previous rebind/restore shortcut.
  reopened.change(state => { state.materials = initial().materials; state.newLearning = true; });
  const freshComparison = await reopened.engine.compare();
  await assert.rejects(reopened.engine.bindLocal(freshComparison, true, true), /等待手动删除/);
  await assert.rejects(reopened.engine.prepareRestore(cloud.heads.get('A').snapshotId), /不恢复旧记录/);
  assert.equal(reopened.engine.view().localReset, true);
  assert.equal(cloud.stats.commits, 2);
  // Equal content never silently rebinds after a reset, including a different account.
  const equal = local(cloud);
  await equal.context.PocketDataDeletion.clearLocal(equal.context.PocketDataDeletion.preview().raw);
  const equalReopen = local(cloud, null, equal.store);
  await equalReopen.engine.setUser({ uid: 'B' });
  equal.store.set('cognivex-pocket-state', other.store.get('cognivex-pocket-state'));
  for (const key of equalReopen.context.PocketCloudBackup.DATA_KEYS.slice(1)) equal.store.set(key, other.store.get(key));
  await equalReopen.engine.compare();
  assert.equal(equalReopen.engine.view().localReset, true);
  assert.equal(equalReopen.engine.view().bound, false);
  // Failure rolls back local entries; pause persists and safe retry succeeds.
  const failure = local(cloud), original = failure.store.get('cognivex-pocket-state');
  failure.fail('pocket-training-sop-model-v1');
  await assert.rejects(failure.context.PocketDataDeletion.clearLocal(original), /清空失败/);
  assert.equal(failure.store.get('cognivex-pocket-state'), original);
  assert.equal(failure.engine.view().localReset, true);
  await failure.context.PocketDataDeletion.clearLocal(original);
  assert.equal(failure.store.has('cognivex-pocket-state'), false);
  const failPause = local(cloud); failPause.fail('pocket-local-reset-v1');
  await assert.rejects(failPause.context.PocketDataDeletion.clearLocal(failPause.context.PocketDataDeletion.preview().raw), /Quota/);
  assert.equal(failPause.store.has('cognivex-pocket-state'), true);
  // An offline, unbound device can clear locally without touching Firebase.
  const offline = local(cloud); offline.online(false);
  await offline.context.PocketDataDeletion.clearLocal(offline.context.PocketDataDeletion.preview().raw);
  assert.equal(offline.store.has('cognivex-pocket-state'), false);
  // Isolation barrier drains an old upload, without publishing its partial snapshot.
  const raceCloud = remote(), racing = local(raceCloud); await bind(racing);
  racing.change(state => { state.changed = true; }); racing.advance(400);
  let release, entered;
  const reached = new Promise(resolve => { entered = resolve; });
  raceCloud.stats.onWrite = () => { entered(); return new Promise(resolve => { release = resolve; }); };
  const upload = racing.engine.retry(); await reached;
  const clearing = racing.context.PocketDataDeletion.clearLocal(racing.context.PocketDataDeletion.preview().raw);
  await new Promise(resolve => setImmediate(resolve));
  assert.equal(racing.store.has('cognivex-pocket-state'), true);
  release(); await upload; await clearing;
  assert.equal(raceCloud.stats.commits, 1);
  assert.equal(raceCloud.manifests.size, 1);
  assert.equal(racing.store.has('cognivex-pocket-state'), false);
  await racing.engine.retry(); assert.equal(raceCloud.stats.commits, 1);
  // An unfinished restore journal must not resurrect data on reopen.
  racing.store.set('pocket-cloud-restore-journal-v1', JSON.stringify({ version: 1, originalControl: {}, entries: [{ key: 'cognivex-pocket-state', content: original }] }));
  local(raceCloud, null, racing.store);
  assert.equal(racing.store.has('cognivex-pocket-state'), false);
  // Missing browser locks or another open Pocket window blocks mutation.
  const blocked = local(cloud), blockedBefore = JSON.stringify([...blocked.store]);
  blocked.context.navigator.locks.request = async (name, options, fn) => options.mode === 'exclusive' ? fn(null) : fn({ name });
  await assert.rejects(blocked.context.PocketDataDeletion.clearLocal(blocked.context.PocketDataDeletion.preview().raw), /关闭其他/);
  assert.equal(JSON.stringify([...blocked.store]), blockedBefore);
  blocked.context.navigator.locks = null;
  await assert.rejects(blocked.context.PocketDataDeletion.clearLocal(blocked.context.PocketDataDeletion.preview().raw), /安全隔离/);
  assert.equal(JSON.stringify([...blocked.store]), blockedBefore);
  // A network operation that cannot finish is a visible failure, never a reset success.
  const stalledCloud = remote(), stalled = local(stalledCloud); await bind(stalled);
  stalled.change(state => { state.changed = true; }); stalled.advance(400);
  let unblock, onEntered;
  const started = new Promise(resolve => { onEntered = resolve; });
  stalledCloud.stats.onWrite = () => { onEntered(); return new Promise(resolve => { unblock = resolve; }); };
  const pendingUpload = stalled.engine.retry(); await started;
  const pendingClear = stalled.context.PocketDataDeletion.clearLocal(stalled.context.PocketDataDeletion.preview().raw);
  const rejected = assert.rejects(pendingClear, /旧云端任务尚未结束/);
  await new Promise(resolve => setImmediate(resolve));
  const timeout = [...stalled.timers.values()].find(timer => timer.delay === 10000);
  assert.ok(timeout); timeout.fn(); await rejected;
  assert.equal(stalled.store.has('cognivex-pocket-state'), true);
  assert.equal(stalled.engine.view().localReset, true);
  unblock(); await pendingUpload;
  await stalled.context.PocketDataDeletion.clearLocal(stalled.context.PocketDataDeletion.preview().raw);
  assert.equal(stalledCloud.stats.commits, 1);
  assert.equal(stalled.store.has('cognivex-pocket-state'), false);
  // A retrying transaction cannot publish after the local pause invalidates its guard.
  const commitCloud = remote(), committing = local(commitCloud); await bind(committing);
  committing.change(state => { state.changed = true; }); committing.advance(400);
  let finishCommit, commitEntered;
  const committingStarted = new Promise(resolve => { commitEntered = resolve; });
  commitCloud.stats.onCommit = () => { commitEntered(); return new Promise(resolve => { finishCommit = resolve; }); };
  const pendingCommit = committing.engine.retry(); await committingStarted;
  const clearDuringCommit = committing.context.PocketDataDeletion.clearLocal(committing.context.PocketDataDeletion.preview().raw);
  await new Promise(resolve => setImmediate(resolve));
  finishCommit(); await pendingCommit; await clearDuringCommit;
  assert.equal(commitCloud.stats.commits, 1);
  assert.equal(commitCloud.manifests.size, 1);
  console.log('PASS: CLEAR and cancellation, local-only complete scope, auth/unrelated/other-device isolation, immutable latest/history, upload barrier, offline/failure rollback/retry, persistent pause, no implicit restore/rebind, manual-deletion gate blocks all rebind and restore shortcuts.');
})().catch(error => { console.error(error); process.exitCode = 1; });
