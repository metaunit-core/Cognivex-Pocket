'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { local, remote, bind } = require('./helpers/pocket-cloud-fixture.cjs');
const { seed } = require('./helpers/pocket-learning-ui.cjs');
module.exports = (async () => {
  const cloud = remote(), state = seed(1);
  state.materials[0].groups[0].end = 20;
  const device = local(cloud, state), otherDevice = local(cloud, state);
  const otherBefore = JSON.stringify([...otherDevice.store]);
  await bind(device);
  const commits = cloud.stats.commits, originalSnapshot = cloud.heads.get('A').snapshotId;
  const source = fs.readFileSync(path.join(__dirname, '../js/focus-review.js'), 'utf8');
  for (const name of ['daily-reverse-review', 'review-admission']) vm.runInContext(fs.readFileSync(path.join(__dirname, '../js/' + name + '.js'), 'utf8'), device.context);
  vm.runInContext(source, device.context);
  const model = device.context.PocketFocusReview;
  model.root(device.context.PocketStorage.loadState());
  await device.engine.retry();
  assert.equal(cloud.stats.commits, commits, 'loading an absent focus root must not create a cloud change');
  device.change(next => {
    device.context.PocketReviewAdmission.markClicked(next, 'focus', 100);
    model.add(next, 'm1', 0, '3,7,12');
    const id = model.create(next, '数学', 3, model.available(next, '数学').map(question => question.id));
    model.start(next, id, 100);
    const run = model.active(next).run.id;
    model.transition(next, run, 'videoDone', {}, 101);
    model.transition(next, run, 'finish', { accuracy: '2/3', durationMinutes: '8', notes: 'mock only' }, 102);
    model.transition(next, run, 'finish', {}, 103, 1);
    model.transition(next, run, 'finish', {}, 104, 2);
  });
  device.advance(400); await device.engine.retry();
  assert.equal(cloud.stats.commits, commits + 1);
  const snapshot = await device.engine.readSnapshot('A', cloud.heads.get('A').snapshotId);
  const exported = JSON.parse(snapshot.backup.rawState), stored = JSON.parse(device.store.get('cognivex-pocket-state'));
  assert.equal(JSON.stringify(exported.focusReview), JSON.stringify(stored.focusReview));
  assert.equal(JSON.stringify(exported.materials), JSON.stringify(state.materials));
  assert.equal(exported.focusReview.groups[0].runs[0].completedAt, 104);
  assert.equal(exported.reviewAdmission.focus[0].completedAt, 104);
  assert.equal(exported.reviewAdmission.lastClicked.system, 'focus');
  assert.ok(cloud.manifests.has('A/' + originalSnapshot));
  assert.equal(JSON.stringify([...otherDevice.store]), otherBefore);
  await device.engine.retry(); assert.equal(cloud.stats.commits, commits + 1, 'unchanged focus snapshot remains deduplicated');
  device.engine.dispose(); otherDevice.engine.dispose();
  console.log('PASS: in-memory Firebase adapter captures focus data in existing raw JSON, preserves prior snapshots/other devices, unchanged deduplication and no initialization upload. No SDK/network access.');
})().catch(error => { console.error(error); process.exitCode = 1; });
