'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const { boot, seed } = require('./helpers/pocket-learning-ui.cjs');
const location = new URL('http://localhost:4173/'), key = 'pocket-development-v1:cognivex-pocket-state';
const initial = seed(2);
initial.materials.forEach(material => { material.subject = '数学'; material.groups[0].start = 1; material.groups[0].end = 20; });
let app = boot({ location, focusReview: true });
const model = app.context.PocketFocusReview;
model.add(initial, 'm1', 0, '1、2'); model.add(initial, 'm2', 0, '3、4');
for (let index = 0; index < 2; index++) model.create(initial, '数学', 2, model.available(initial, '数学').slice(0, 2).map(question => question.id));
app = boot({ location, store: new Map([[key, JSON.stringify(initial)]]), focusReview: true });
const walk = node => [node, ...node.children.flatMap(walk)];
const page = () => app.document.getElementById('focus-review');
const text = () => walk(page()).map(node => node.textContent).join('\n');
const click = label => { const node = walk(page()).find(node => node.tag === 'button' && node.textContent === label); assert.ok(node, label); node.fire('click'); };
const fill = (prefix, accuracy, duration) => {
  for (const [id, value] of [[prefix + 'group-latest-accuracy', accuracy], [prefix + 'group-latest-duration', duration]]) {
    const input = app.document.getElementById(id); assert.ok(input, id); input.value = value; input.fire('input');
  }
};
app.document.getElementById('daily-reverse-review-entry').fire('click'); fill('', '8/10', '15');
const dailyBytes = JSON.stringify(app.state().dailyReverseReview);
app.context.PocketLearning.showHome(); app.document.getElementById('start-review-button').fire('click'); fill('', '6/10', '12');
const originals = JSON.stringify(app.state().materials), reverseBytes = JSON.stringify(app.state().materialReviewSession);
app.context.PocketFocusReviewUI.open({ subject: '数学' }); click('复习');
fill('focus-', '1/2', '5');
assert.match(text(), /正确率：1\/2 · 用时：5分钟/);
assert.equal(app.context.PocketFocusReview.active(app.state()).run.metricsScope, 'group');
assert.equal(app.context.PocketFocusReview.active(app.state()).run.questionProgress[0].accuracy, '');
click('输出达标 → 下一步');
assert.equal(app.document.getElementById('focus-group-latest-accuracy').value, '1/2');
assert.equal(app.document.getElementById('focus-group-latest-duration').value, '5');
const runId = app.context.PocketFocusReview.active(app.state()).run.id;
app = boot({ location, store: app.store, focusReview: true });
assert.equal(app.document.getElementById('focus-group-latest-accuracy').value, '1/2');
const beforeFail = app.store.get(key); app.fail.enabled = true; fill('focus-', '0/2', '9'); assert.equal(app.store.get(key), beforeFail);
assert.match(text(), /保存失败/); app.fail.enabled = false; fill('focus-', '1/2', '5'); click('输出达标 → 下一步');
assert.equal(app.state().focusReview.groups[0].runs[0].id, runId);
assert.equal(app.state().focusReview.groups[0].runs.length, 1);
assert.equal(app.state().focusReview.groups[0].runs[0].accuracy, '1/2');
app.context.PocketFocusReviewUI.open({ subject: '数学', focusGroup: initial.focusReview.groups[1].id }); click('复习');
fill('focus-', '3/3', '8'); click('输出达标 → 下一步'); click('输出达标 → 下一步');
assert.match(text(), /正确率：3\/3 · 用时：8分钟/);
const plan = model.groupingPlan(app.state(), '数学', { accuracy: 60 });
assert.deepEqual(JSON.parse(JSON.stringify(plan.questions.map(question => question.number))), [1, 2]);
assert.equal(plan.groupMetrics, 2); assert.equal(plan.unrecorded, 0);
assert.equal(JSON.stringify(app.state().materials), originals); assert.equal(JSON.stringify(app.state().dailyReverseReview), dailyBytes);
assert.equal(JSON.stringify(app.state().materialReviewSession), reverseBytes);
const beforeRegroup = app.state(), histories = JSON.stringify(beforeRegroup.focusReview.groups.map(group => group.runs));
const expected = model.groupingPlan(beforeRegroup, '数学'); model.regroup(beforeRegroup, '数学', 2, { questionIds: expected.questions.map(question => question.id), groupIds: expected.groupIds }, true);
assert.equal(JSON.stringify(beforeRegroup.focusReview.groups.slice(0, 2).map(group => group.runs)), histories);
assert.ok(beforeRegroup.focusReview.groups.slice(2).every(group => group.runs.length === 0));
assert.deepEqual(JSON.parse(JSON.stringify(model.groupingPlan(beforeRegroup, '数学', { accuracy: 60 }).questions.map(question => question.number))), []);
app = boot({ location, store: new Map([[key, JSON.stringify(beforeRegroup)]]), focusReview: true });
app.context.PocketFocusReviewUI.open({ subject: '数学' }); click('全部复习'); fill('focus-', '1/2', '8');
click('输出达标 → 下一步'); click('输出达标 → 下一步');
assert.equal(app.document.getElementById('focus-group-latest-accuracy').value, '');
fill('focus-', '3/3', '12'); click('输出达标 → 下一步'); click('输出达标 → 下一步');
assert.match(text(), /正确率：1\/2 · 用时：8分钟/); assert.match(text(), /正确率：3\/3 · 用时：12分钟/);
assert.equal(app.state().focusReview.allReviews[0].runs[0].accuracy, '');
assert.equal(model.groupingPlan(app.state(), '数学', { accuracy: 60 }).groupMetrics, 2);
assert.deepEqual(JSON.parse(JSON.stringify(model.groupingPlan(app.state(), '数学', { accuracy: 60 }).questions.map(question => question.number))), [1, 2]);
assert.ok(app.state().focusReview.groups.slice(2).every(group => group.runs.length === 1));
assert.deepEqual(app.state().focusReview.groups.slice(2).map(group => group.runs[0].accuracy), ['1/2', '3/3']);
const interleaved = seed(2); interleaved.materials.forEach(material => { material.subject = '数学'; material.groups[0].start = 1; material.groups[0].end = 20; });
for (const [material, number, at] of [['m1', 1, 100], ['m1', 3, 300], ['m2', 2, 200], ['m2', 4, 400]]) model.add(interleaved, material, 0, String(number), false, at);
for (let index = 0; index < 2; index++) model.create(interleaved, '数学', 2, model.available(interleaved, '数学').slice(0, 2).map(question => question.id));
app = boot({ location, store: new Map([[key, JSON.stringify(interleaved)]]), focusReview: true });
app.context.PocketFocusReviewUI.open({ subject: '数学' }); click('全部复习');
fill('focus-', '1/2', '8'); click('输出达标 → 下一步');
fill('focus-', '3/3', '12'); click('输出达标 → 下一步');
assert.equal(app.document.getElementById('focus-group-latest-accuracy').value, '1/2');
assert.equal(app.document.getElementById('focus-group-latest-duration').value, '8');
click('输出达标 → 下一步');
assert.equal(app.state().focusReview.groups[0].runs.length, 1); assert.equal(app.state().focusReview.groups[1].runs.length, 0);
assert.equal(app.document.getElementById('focus-group-latest-accuracy').value, '3/3');
app = boot({ location, store: app.store, focusReview: true });
assert.equal(app.document.getElementById('focus-group-latest-duration').value, '12');
const finalButton = walk(page()).find(node => node.textContent === '输出达标 → 下一步');
click('输出达标 → 下一步'); finalButton.fire('click');
assert.deepEqual(app.state().focusReview.groups.map(group => group.runs.length), [1, 1]);
assert.deepEqual(app.state().focusReview.groups.map(group => group.runs[0].accuracy), ['1/2', '3/3']);
assert.ok(app.state().focusReview.allReviews[0].runs[0].questionProgress.every(record => record.accuracy === '' && record.durationMinutes === ''));
vm.runInContext(fs.readFileSync(path.join(__dirname, '../js/learning-backup.js'), 'utf8'), app.context);
console.log('PASS real original daily/reverse metrics isolation, live Group history sync, 1/2+5 and 3/3+8 independent grades, next/reload persistence, failure safety, truthful Group filtering, archived snapshot association and all-review aggregates.');
(async () => {
  const backup = await app.context.PocketLearningBackup.create();
  assert.equal((await app.context.PocketLearningBackup.verify(JSON.stringify(backup))).valid, true);
  assert.equal(JSON.stringify(JSON.parse(backup.rawState).focusReview), JSON.stringify(app.state().focusReview));
})().catch(error => { console.error(error); process.exitCode = 1; });
