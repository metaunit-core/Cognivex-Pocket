'use strict';
const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const { boot, seed } = require('./helpers/pocket-learning-ui.cjs');
const location = new URL('http://localhost:4173/'), app = boot({ location, focusReview: true });
for (const name of ['learning-backup', 'learning-archive']) vm.runInContext(fs.readFileSync(path.join(__dirname, '../js/' + name + '.js'), 'utf8'), app.context);
const state = seed(2), group = state.materials[0].groups[0];
delete group.latestAccuracyPercent; delete group.latestDurationMinutes;
const done = (id, at, values = {}) => ({ id, startedAt: at, completedAt: at + 1, outputCompleted: true, ...values });
group.runs = [done('one', 10, { accuracy: '1/2', durationMinutes: '8' }), done('two', 20), done('three', 30), done('four', 40, { accuracy: '2/2', durationMinutes: '5' })];
const render = () => app.context.PocketLearningArchive.render(JSON.stringify(state));
const first = () => render().split('**分组记录**')[1].split('#### ')[0];
assert.match(first(), /\| 第1组 \| 1 \| 2\/2 \| 5分钟 \|/);
assert.match(render(), /Material：2\n- Group：2\n- Run：5/);
group.runs.push(done('five', 50, { accuracy: '0/2', durationMinutes: '' }));
assert.match(first(), /\| 第1组 \| 1 \| 0\/2 \| 5分钟 \|/);
group.runs.push(done('draft', 60, { completedAt: null, accuracy: '2/2', durationMinutes: 99 }));
group.runs.push(done('invalid', 70, { outputCompleted: false, accuracy: '2/2', durationMinutes: 99 }));
assert.doesNotMatch(first(), /99分钟/);
group.latestAccuracyRatio = '0/2'; group.latestAccuracyPercent = 0; group.latestDurationMinutes = 0;
assert.match(first(), /\| 0\/2 \| 0分钟 \|/);
delete group.latestAccuracyRatio; delete group.latestAccuracyPercent; delete group.latestDurationMinutes;
// Daily per-Group records are a separate history store; ID matching and round deduplication preserve ordinals.
const dailyRound = { id: 'daily', tasks: [{ materialId: 'm1', groupId: 'id:' + group.id, status: 'completed', run: done('daily-run', 45) }] };
state.dailyReverseReview = { version: 1, saveOrder: ['m1', 'm2'], history: [dailyRound], round: dailyRound };
assert.match(first(), /\| 0\/2 \| 5分钟 \|/);
assert.doesNotMatch(first(), /最新成绩记录于/);
delete state.dailyReverseReview;
const model = app.context.PocketFocusReview;
state.materials.forEach(m => { m.groups[0].start = 1; m.groups[0].end = 20; });
model.add(state, 'm1', 0, '1、2'); model.add(state, 'm2', 0, '3、4');
for (let i = 0; i < 2; i++) model.create(state, '数学', 2, model.available(state, '数学').slice(0, 2).map(q => q.id));
const ids = state.focusReview.groups.map(g => g.id);
const finish = (id, values) => { model.start(state, id); while (model.active(state)) model.transition(state, model.active(state).run.id, 'finish', values); };
finish(ids[0], { accuracy: '1/2', durationMinutes: '8' });
finish(ids[0], { accuracy: '', durationMinutes: '' });
finish(ids[0], { accuracy: '2/2', durationMinutes: '' });
const focus = () => render().split('## 二、重点复习系统学习数据')[1];
assert.match(focus(), /\| 2\/2 \| 8分钟 \|/);
model.start(state, ids[0]); model.transition(state, model.active(state).run.id, 'save', { accuracy: '0/2', durationMinutes: '999' });
assert.doesNotMatch(focus(), /999分钟/);
finish(ids[0], { accuracy: '1/2', durationMinutes: '6' });
model.startAll(state, '数学');
while (model.active(state)) model.transition(state, model.active(state).run.id, 'finish', { accuracy: '2/2', durationMinutes: '5' });
assert.equal((focus().match(/\| 2\/2 \| 5分钟 \|/g) || []).length, 2);
assert.doesNotMatch(focus(), /最新成绩记录于|完整 Group 复习|第\d+次/);
const savedGroup = state.focusReview.groups[0]; savedGroup.runs.push(JSON.parse(JSON.stringify(savedGroup.runs.at(-1))));
assert.equal((focus().match(/\| 2\/2 \| 5分钟 \|/g) || []).length, 2); // Duplicate copies do not add display rows.
savedGroup.runs.push(done('legacy-questions', Date.now() + 1, { progressVersion: 1, accuracy: '0/1', durationMinutes: 999, questionProgress: [] }));
savedGroup.runs.push(done('wrong-all-round', Date.now() + 2, { metricsScope: 'all-groups', accuracy: '0/1', durationMinutes: 999 }));
assert.doesNotMatch(focus(), /999分钟/);
assert.match(focus(), /\| 2\/2 \| 5分钟 \|/);
const plan = model.groupingPlan(state, '数学'); model.regroup(state, '数学', 2, { questionIds: plan.questions.map(q => q.id), groupIds: plan.groupIds }, true);
assert.match(focus(), /\| 未填写 \| 未填写 \|/);
assert.doesNotMatch(focus(), /第5次/);
const raw = JSON.stringify(state), stores = JSON.stringify([...app.store]); render();
assert.equal(JSON.stringify(state), raw); assert.equal(JSON.stringify([...app.store]), stores);
assert.doesNotMatch(render(), /训练明细|训练历史|第1次训练.*1\/2/);
console.log('PASS localhost summary ordinals, split sources, missing/zero/invalid/draft fields, daily history, all-review copies, regroup isolation and read-only state.');
