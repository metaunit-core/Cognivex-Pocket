for (let index = 1; index < 5; index++) walk(old.document.getElementById('focus-review')).find(node => node.textContent === '输出达标 → 下一步').fire('click');
assert.equal(old.state().focusReview.session, null, 'legacy VIDEO checkpoint must adapt without changing an original group');
assert.equal(old.state().focusReview.groups[1].runs[0].questionProgress[0].notes, '保留原有备注');
console.log('PASS compact strips, hidden IDs/invalid links, 5/4/3 direct grouping, ordered review, shared original OUTPUT/metrics components, independent autosave, persistence, legacy checkpoint and atomic daily admission.');
