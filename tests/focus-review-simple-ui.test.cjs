assert.equal(app.state().focusReview.session, null);
app.context.PocketFocusReviewUI.open({ subject: '物理' });
assert.equal(walk(cards()[0]).find(node => node.textContent === '复习').disabled, false);
assert.equal(walk(cards()[1]).find(node => node.textContent === '复习').disabled, false);
assert.equal(JSON.stringify(app.state().dailyReverseReview), originalDaily);
assert.equal(JSON.stringify(app.state().materials), originalMaterials);
