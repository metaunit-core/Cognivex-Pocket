'use strict';
const assert = require('node:assert/strict');
const { boot, seed } = require('./helpers/pocket-learning-ui.cjs');
const key = 'pocket-development-v1:cognivex-pocket-state', location = new URL('http://localhost:4173/');
const initial = seed(2); initial.materials.forEach(material => { material.groups[0].start = 1; material.groups[0].end = 20; });
initial.materials[0].subject = '数学'; initial.materials[0].title = '函数'; initial.materials[1].subject = '物理'; initial.materials[1].title = '受力分析';
let app = boot({ location, focusReview: true });
app.context.PocketFocusReview.add(initial, 'm1', 0, '4'); app.context.PocketFocusReview.add(initial, 'm1', 0, '3');
app.context.PocketFocusReview.add(initial, 'm1', 0, '7'); app.context.PocketFocusReview.setStatus(initial, initial.focusReview.questions[2].id, 'mastered');
app.context.PocketFocusReview.add(initial, 'm2', 0, '2');
const raw = JSON.stringify(initial);
app = boot({ location, store: new Map([[key, raw]]), focusReview: true });
const walk = node => [node, ...node.children.flatMap(walk)];
const page = () => app.document.getElementById('focus-review');
app.context.PocketFocusReviewUI.open();
assert.ok(!walk(page()).some(node => node.className === 'focus-question focus-strip'));
const sections = page().children.filter(node => node.className === 'practice-condition');
assert.equal(sections.length, 2);
app.context.scrollY = 125;
const scrolls = []; app.context.scrollTo = (left, top) => scrolls.push(top);
walk(sections[0]).find(node => node.textContent === '重点题列表 →').fire('click');
assert.ok(walk(page()).some(node => node.tag === 'h1' && node.textContent === '重点题列表'));
assert.ok(walk(page()).some(node => node.textContent === '数学 · 函数'));
assert.ok(walk(page()).some(node => node.textContent === '第 4、3 题'));
assert.ok(!walk(page()).some(node => /受力分析|第 7 题|管理题目/.test(node.textContent)));
assert.ok(!walk(page()).some(node => node.tag === 'input' || node.tag === 'textarea'));
assert.equal(app.store.get(key), raw);
const restored = boot({ location, store: app.store, focusReview: true });
assert.ok(walk(restored.document.getElementById('focus-review')).some(node => node.tag === 'h1' && node.textContent === '重点题列表'));
walk(page()).find(node => node.textContent === '← 返回').fire('click');
assert.equal(scrolls.at(-1), 125);
assert.ok(walk(page()).some(node => node.tag === 'h1' && node.textContent === '重点复习系统'));
assert.ok(!walk(page()).some(node => node.className === 'focus-question focus-strip'));
walk(page().children.filter(node => node.className === 'practice-condition')[1]).find(node => node.textContent === '重点题列表 →').fire('click');
assert.ok(walk(page()).some(node => node.textContent === '物理 · 受力分析'));
assert.ok(!walk(page()).some(node => node.textContent === '数学 · 函数'));
assert.equal(app.store.get(key), raw);
console.log('PASS per-subject list routes, home card removal, stable card order/status filtering, back/reload, no extra inputs and unchanged learning state.');
