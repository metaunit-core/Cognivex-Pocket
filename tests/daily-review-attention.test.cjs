'use strict';
const assert = require('node:assert/strict'), fs = require('node:fs');
const { boot, seed } = require('./helpers/pocket-learning-ui.cjs');
const MAIN = 'cognivex-pocket-state';
const clock = { now: new Date(2026, 9, 18, 9).getTime() };
const store = new Map([[MAIN, JSON.stringify(seed(2))]]);
const attention = button => button.className.split(/\s+/).includes('daily-review-attention');
let ui = boot({ store, clock });
let button = ui.document.getElementById('daily-reverse-review-entry');
const fold = ui.all().find(node => node.className === 'learned-content-fold');
assert.ok(fold); assert.equal(Boolean(fold.open), false);
assert.equal(fold.children[0].textContent, '已学内容');
assert.equal(attention(button), true);
assert.equal(ui.state().dailyReverseReview, undefined); // Rendering writes no click/completion state.
fold.open = true;
assert.equal(attention(button), true); assert.equal(fold.children.find(n => n.tag === 'ul').children.length, 2);
const before = structuredClone(ui.state());
button.fire('click');
assert.deepEqual(ui.state().dailyReverseReview.clickedDays, ['2026-10-18']);
assert.equal(ui.state().dailyReverseReview.round.index, 0);
assert.equal(ui.context.PocketDailyReverse.needsReview(ui.state()), true);
assert.deepEqual(ui.state().materials, before.materials);
assert.deepEqual(ui.state().review, before.review);
assert.equal(attention(ui.document.getElementById('daily-reverse-review-entry')), false);
ui.button('返回已学内容').fire('click');
assert.equal(attention(ui.document.getElementById('daily-reverse-review-button')), false);
assert.equal(ui.context.PocketMaterialReview.canCreate(ui.state()), false);
ui = boot({ store, clock });
assert.equal(attention(ui.document.getElementById('daily-reverse-review-entry')), false);
const closed = ui.all().find(node => node.className === 'learned-content-fold');
assert.equal(Boolean(closed.open), false);
const page = JSON.stringify(ui.context.PocketNavigation.pocket()), round = JSON.stringify(ui.state().dailyReverseReview.round);
clock.now = new Date(2026, 9, 19, 9).getTime();
ui.fire('focus'); ui.fire('pageshow'); ui.fire('visibilitychange');
assert.equal(attention(ui.document.getElementById('daily-reverse-review-entry')), true);
assert.equal(Boolean(closed.open), false);
assert.equal(JSON.stringify(ui.context.PocketNavigation.pocket()), page);
assert.equal(JSON.stringify(ui.state().dailyReverseReview.round), round);
ui.document.getElementById('daily-reverse-review-entry').fire('click');
assert.equal(attention(ui.document.getElementById('daily-reverse-review-entry')), false);
assert.deepEqual(ui.state().dailyReverseReview.clickedDays, ['2026-10-18', '2026-10-19']);
ui.button('输出达标 → 下一步').fire('click'); ui.button('输出达标 → 下一步').fire('click');
assert.equal(ui.context.PocketDailyReverse.needsReview(ui.state()), false);
assert.equal(attention(ui.document.getElementById('daily-reverse-review-entry')), false);
// Completed legacy rounds do not animate even when no click record exists.
const complete = ui.state(); delete complete.dailyReverseReview.clickedDays;
const done = boot({ store: new Map([[MAIN, JSON.stringify(complete)]]), clock });
assert.equal(attention(done.document.getElementById('daily-reverse-review-entry')), false);
const empty = boot({ store: new Map([[MAIN, JSON.stringify(seed(0))]]), clock });
assert.equal(attention(empty.document.getElementById('daily-reverse-review-entry')), false);
// Local simulated date is used without changing any round or real timestamp until explicit start.
const prefix = 'pocket-development-v1:';
const local = boot({ store: new Map([[prefix + MAIN, JSON.stringify(seed(1))]]), clock,
  location: new URL('http://127.0.0.1:5500') });
local.context.PocketDailyTestDate.set('2030-02-01');
local.document.getElementById('daily-reverse-review-entry').fire('click');
assert.deepEqual(local.state().dailyReverseReview.clickedDays, ['2030-02-01']);
const localRound = JSON.stringify(local.state().dailyReverseReview.round);
local.context.PocketDailyTestDate.set('2030-02-02');
assert.equal(attention(local.document.getElementById('daily-reverse-review-entry')), true);
assert.equal(JSON.stringify(local.state().dailyReverseReview.round), localRound);
local.context.PocketDailyTestDate.set('2030-02-01');
assert.equal(attention(local.document.getElementById('daily-reverse-review-entry')), false);
