'use strict';
const assert = require('node:assert/strict');
const { boot, seed } = require('./helpers/pocket-learning-ui.cjs');
const key = 'pocket-development-v1:cognivex-pocket-state', location = new URL('http://localhost:4173/');
const initial = seed(2); initial.materials.forEach(material => { material.subject = '数学'; material.groups[0].start = 1; material.groups[0].end = 20; });
initial.materials[0].title = '圆锥'; initial.materials[1].title = '函数';
let app = boot({ location, focusReview: true }), model = app.context.PocketFocusReview;
model.add(initial, 'm1', 0, '2、4'); model.add(initial, 'm2', 0, '1');
const groupId = model.create(initial, '数学', 3, model.available(initial, '数学').map(question => question.id));
const materials = JSON.stringify(initial.materials), members = JSON.stringify(initial.focusReview.groups[0].members);
model.start(initial, groupId);
app = boot({ location, store: new Map([[key, JSON.stringify(initial)]]), focusReview: true });
const walk = node => [node, ...node.children.flatMap(walk)];
const page = () => app.document.getElementById('focus-review');
const press = label => { const node = walk(page()).find(node => node.tag === 'button' && node.textContent === label && !node.disabled); assert.ok(node, label); node.fire('click'); };
const openRun = () => app.context.PocketFocusReviewUI.open({ subject: '数学', focusGroup: groupId });
const removeFirst = () => {
  press('移除'); const checkbox = walk(page()).find(node => node.tag === 'input' && node.type === 'checkbox');
  checkbox.checked = true; checkbox.fire('change'); press('确认移出所选题目');
};
function checkLibrary(expectedCards, count) {
  app.context.PocketFocusReviewUI.open();
  const section = page().children.find(node => node.className === 'practice-condition');
  assert.ok(section.children.some(node => node.textContent.startsWith('重点题：' + count + '道')));
  assert.ok(!walk(page()).some(node => node.className === 'focus-question focus-strip'));
  press('重点题列表 →');
  const cards = page().children.filter(node => node.className === 'focus-question focus-strip');
  assert.deepEqual(cards.map(card => card.children.slice(0, 2).map(node => node.textContent)), expectedCards);
  assert.ok(!walk(page()).some(node => /管理题目|已熟练、已移出或来源不可用的题目/.test(node.textContent)));
  const effective = app.context.PocketFocusReview;
  assert.equal(effective.groupingPlan(app.state(), '数学').questions.length, count);
  assert.equal(effective.allQuestions(app.state(), '数学').length, count);
}
openRun(); removeFirst();
checkLibrary([['数学 · 圆锥', '第 4 题'], ['数学 · 函数', '第 1 题']], 2);
assert.match(app.document.getElementById('focus-review-statistics').textContent, /重点题 2 道/);
openRun(); assert.equal(app.context.PocketFocusReview.active(app.state()).question.number, 4);
removeFirst();
checkLibrary([['数学 · 函数', '第 1 题']], 1);
app = boot({ location, store: app.store, focusReview: true });
checkLibrary([['数学 · 函数', '第 1 题']], 1);
assert.equal(JSON.stringify(app.state().materials), materials);
assert.equal(JSON.stringify(app.state().focusReview.groups[0].members), members);
assert.equal(app.state().focusReview.groups[0].runs[0].questionProgress[0].resolution, 'removed');
openRun(); press('输出达标 → 下一步');
const completedCards = page().children.filter(node => node.className === 'focus-question focus-strip');
assert.deepEqual(completedCards.map(card => card.children[1].textContent), ['第 1 题']);
const state = app.state(); model.start(state, groupId);
assert.deepEqual(JSON.parse(JSON.stringify(model.active(state).run.members.map(question => question.number))), [1]);
console.log('PASS removal immediately filters effective material cards/numbers/counts, hides empty cards, retains collapsed management/history, persists on reload and filters future queues/regrouping without rewriting members/sources.');
