assert.equal(boxes().find(n => n['data-question-number'] === '4').checked, true);
open(); assert.equal(boxes().find(n => n['data-question-number'] === '4').checked, true);
app.fail.enabled = true; add(); app.fail.enabled = false;
assert.equal(app.store.get(key), before); assert.equal(boxes().find(n => n['data-question-number'] === '4').checked, true);
add(); const first = app.state().focusReview.questions[0];
assert.equal(first.number, 4); assert.equal(first.materialId, 'm1'); assert.equal(first.groupId, 'g1'); assert.equal(first.subjectName, '数学');
assert.equal(app.state().focusReview.questions.length, 1); assert.equal(app.state().materials[1].groups[0].keyQuestions, initial.materials[1].groups[0].keyQuestions);
assert.equal(app.state().materials[0].groups[0].keyQuestions, '旧文本与备注\n第4题');
assert.equal(boxes().find(n => n['data-question-number'] === '4').disabled, true);
add(); assert.equal(app.state().focusReview.questions.length, 1);
check(2); check(2, false); assert.equal(app.state().focusReview.questions[0].id, first.id);
const state = app.state(); model.setStatus(state, first.id, 'mastered'); model.add(state, 'm1', 0, '3'); model.setStatus(state, state.focusReview.questions[1].id, 'removed');
app = boot({ location, focusReview: true, store: new Map([[key, JSON.stringify(state)]]) }); open();
assert.ok(boxes().every(n => !n.checked)); check(1); add();
assert.deepEqual(app.state().focusReview.questions.slice(0, 2).map(q => q.status), ['mastered', 'removed']);
assert.equal(app.state().focusReview.questions[0].events.length, state.focusReview.questions[0].events.length);
check(4); add();
assert.equal(app.state().focusReview.questions[0].id, first.id);
assert.equal(app.state().focusReview.questions[0].status, 'active');
assert.equal(app.state().focusReview.questions[0].events.length, state.focusReview.questions[0].events.length + 1);
