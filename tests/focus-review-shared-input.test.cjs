const panel = () => app.document.getElementById('group-key-questions-panel');
const boxes = () => walk(panel()).filter(n => n.type === 'checkbox');
const check = (number, checked = true) => { const input = boxes().find(n => n['data-question-number'] === String(number)); assert.ok(input, String(number)); input.checked = checked; input.fire('change'); };
const add = () => { const button = walk(panel()).find(n => n.tag === 'button' && n.textContent === '加入重点复习系统'); button.fire('click'); return button; };
const open = () => { app.context.PocketLearning.showHome(); app.document.getElementById('daily-reverse-review-entry').fire('click'); };
