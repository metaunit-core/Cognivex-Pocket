'use strict';
const assert = require('node:assert/strict');
const { boot, seed } = require('./helpers/pocket-learning-ui.cjs');
const key = 'pocket-development-v1:cognivex-pocket-state', location = new URL('http://localhost:4173/');
const walk = node => [node, ...node.children.flatMap(walk)];
const initial = seed(1); initial.materials[0].groups[0].start = 1; initial.materials[0].groups[0].end = 20;
let app = boot({ location, store: new Map([[key, JSON.stringify(initial)]]), focusReview: true });
app.context.PocketLearning.showHome(); app.document.getElementById('daily-reverse-review-entry').fire('click');
const panel = app.document.getElementById('group-key-questions-panel'), input = app.document.getElementById('group-key-questions');
const collection = walk(panel).find(node => node.className === 'focus-collection');
assert.ok(collection); assert.equal(walk(collection).filter(node => node.tag === 'input' || node.tag === 'textarea').length, 0);
assert.equal(walk(panel).filter(node => node.textContent === '加入重点复习系统').length, 1);
assert.equal(walk(panel).filter(node => node.tag === 'textarea').length, 1);
const press = (parent, label) => { const button = walk(parent).find(node => node.tag === 'button' && node.textContent === label); assert.ok(button, label); button.fire('click'); };
input.value = '第3、7、12题';
input.fire('input');
assert.equal(app.state().materials[0].groups[0].keyQuestions, '第3、7、12题');
press(collection, '加入重点复习系统');
assert.deepEqual(app.state().focusReview.questions.map(question => question.number), [3, 7, 12]);
assert.equal(input.value, '第3、7、12题');
press(collection, '加入重点复习系统'); assert.equal(app.state().focusReview.questions.length, 3);
const before = app.store.get(key); input.value = '第30题'; press(collection, '加入重点复习系统'); assert.equal(app.store.get(key), before);
input.value = 'not a question'; press(collection, '加入重点复习系统'); assert.equal(app.store.get(key), before);
input.value = '第4题'; app.fail.enabled = true; press(collection, '加入重点复习系统');
assert.equal(app.store.get(key), before); assert.equal(input.value, '第4题'); app.fail.enabled = false;
const uncertain = seed(1); delete uncertain.materials[0].groups[0].start; delete uncertain.materials[0].groups[0].end;
app = boot({ location, store: new Map([[key, JSON.stringify(uncertain)]]), focusReview: true });
const parent = app.document.createElement('section'), original = app.document.createElement('textarea');
parent.append(original); app.document.body.append(parent);
app.context.PocketFocusReviewUI.collection(parent, 'm1', 0, original);
const block = walk(parent).find(node => node.className === 'focus-collection');
original.value = '第3、7题'; const uncertainBefore = app.store.get(key);
press(block, '加入重点复习系统'); assert.equal(app.store.get(key), uncertainBefore);
assert.ok(walk(block).some(node => node.textContent.includes('无法自动核实题号范围')));
press(block, '取消'); assert.equal(app.store.get(key), uncertainBefore);
press(block, '加入重点复习系统'); original.value = '第8题'; press(block, '确认'); assert.equal(app.store.get(key), uncertainBefore);
press(block, '加入重点复习系统'); press(block, '确认');
assert.equal(app.state().focusReview.questions[0].number, 8); assert.equal(original.value, '第8题');
assert.equal(walk(block).filter(node => node.tag === 'input' || node.tag === 'textarea').length, 0);
console.log('PASS shared original textarea, preserved contents, dedup/illegal/range checks, failure safety, explicit uncertain-range confirmation/cancel and stale confirmation rejection.');
