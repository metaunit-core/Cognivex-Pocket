  assert.equal(deleteCalls, 0); assert.equal(readCalls, 0);
  assert.equal(JSON.stringify([...other.store]), otherBefore);
  await device.engine.retry(); await device.fire();
  const reopened = local(cloud, null, device.store), reopenedService = load(reopened);
