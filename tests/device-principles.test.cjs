'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { boot } = require('./helpers/pocket-learning-ui.cjs');
const html = fs.readFileSync(path.join(__dirname, '../index.html'), 'utf8');
assert.match(html, /<details id="learned-material-details"[\s\S]*?<\/details>\s*<button id="device-principles-entry" class="practice-entry"/);
const script = fs.readFileSync(path.join(__dirname, '../js/device-principles.js'), 'utf8');
const app = boot();
vm.runInContext(script, app.context);
app.context.PocketLearning.showHome();
const before = app.store.get('cognivex-pocket-state');
for (const expanded of [false, true]) {
  app.nodes['learned-material-details'].open = expanded;
  app.context.scrollY = 320;
  app.nodes['device-principles-entry'].fire('click');
  const page = app.document.getElementById('device-principles');
  assert.equal(page.hidden, false);
  assert.equal(app.nodes['pocket-main'].hidden, true);
  const walk = node => [node, ...node.children.flatMap(walk)];
  const content = walk(page).map(node => node.textContent).join(' ');
  for (const text of ['① 电脑｜开发环境', '② iPad｜正式学习环境', '③ 手机｜ChatGPT 辅助理解', '④ 自由笔记｜独立输出', '电脑打开正式 GitHub Pages 网站仍属于正式环境。', 'Firebase 自动备份不等于多设备实时同步。', '不要直接复制、粘贴 ChatGPT 聊天记录作为自己的学习笔记。', 'Pocket 查看任务 → iPad 独立做题 → 手机 ChatGPT 提问弄懂 → 放下手机 → 自由笔记独立输出 → Pocket 记录与复习 → 下一组', 'AI 帮我弄懂，我自己脱离提示独立复现。']) assert.ok(content.includes(text));
  assert.equal(walk(page).filter(node => ['input', 'textarea', 'select'].includes(node.tag)).length, 0);
  page.children[0].fire('click');
  assert.equal(page.hidden, true);
  assert.equal(app.nodes['pocket-main'].hidden, false);
  assert.equal(app.nodes['learned-material-details'].open, expanded);
  assert.equal(app.context.scrollY, 320);
  assert.equal(app.store.get('cognivex-pocket-state'), before);
}
app.nodes['device-principles-entry'].fire('click');
const reopened = boot({ store: app.store });
vm.runInContext(script, reopened.context);
reopened.context.PocketNavigation.restore();
assert.equal(reopened.document.getElementById('device-principles').hidden, false);
reopened.nodes['pocket-home-button'].fire('click');
assert.equal(reopened.document.getElementById('device-principles').hidden, true);
console.log('PASS: independent guide, entry outside details, content, return/scroll/expansion, reload/home and unchanged learning data.');
