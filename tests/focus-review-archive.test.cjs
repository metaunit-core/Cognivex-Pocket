'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const { boot, seed } = require('./helpers/pocket-learning-ui.cjs');
const location = new URL('http://localhost:4173/');
const app = boot({ location, focusReview: true }), state = seed(2), model = app.context.PocketFocusReview;
state.materials.forEach(material => { material.subject = '数学'; material.title = '同名资料'; material.groups[0].start = 1; material.groups[0].end = 20; });
const at = new Date(2026, 9, 21, 9).getTime();
model.add(state, 'm1', 0, '4', false, at);
model.add(state, 'm2', 0, '4', false, at + 1);
model.add(state, 'm1', 0, '5、6', false, at + 1);
const groupId = model.create(state, '数学', 2, [state.focusReview.questions[0].id, state.focusReview.questions[1].id], at + 2);
model.start(state, groupId, at + 3);
let run = model.active(state).run;
model.transition(state, run.id, 'finish', { accuracy: '1/2', durationMinutes: '15', notes: '第一次心得 <script>' }, at + 4, 0);
model.transition(state, run.id, 'finish', { accuracy: '8/10', durationMinutes: '12', notes: '另一资料心得' }, at + 5, 1);
model.start(state, groupId, at + 6); run = model.active(state).run;
model.transition(state, run.id, 'finish', { accuracy: '0/2', durationMinutes: '0', notes: '第二轮' }, at + 7, 0);
model.transition(state, run.id, 'finish', { accuracy: '8/10', durationMinutes: '15' }, at + 8, 1);
model.setStatus(state, state.focusReview.questions[2].id, 'mastered', at + 9);
model.setStatus(state, state.focusReview.questions[3].id, 'removed', at + 10);
model.add(state, 'm1', 0, '7', false, at + 11);
const emptyGroup = model.create(state, '数学', 1, [state.focusReview.questions[4].id], at + 12);
const allId = model.startAll(state, '数学', at + 13), allRun = model.active(state).run;
for (let index = 0; index < 3; index++) model.transition(state, allRun.id, 'finish', {}, at + 14 + index, index);
state.materials[0].title = '函数改名';
model.start(state, emptyGroup, at + 18);
model.add(state, 'm1', 0, '8', false, at + 19);
let cloudCalls = 0;
app.context.PocketCloudBackup = { upload() { cloudCalls++; throw Error('Unexpected cloud call'); }, restore() { cloudCalls++; throw Error('Unexpected cloud call'); }, delete() { cloudCalls++; throw Error('Unexpected cloud call'); } };
vm.runInContext(fs.readFileSync(path.join(__dirname, '../js/learning-backup.js'), 'utf8'), app.context);
vm.runInContext(fs.readFileSync(path.join(__dirname, '../js/learning-archive.js'), 'utf8'), app.context);
const raw = JSON.stringify(state), storeBefore = JSON.stringify([...app.store]);
const markdown = app.context.PocketLearningArchive.render(raw);
assert.match(markdown, /^# Cognivex Pocket 学习档案/);
assert.ok(markdown.indexOf('## 一、已学习全部资料的学习数据') < markdown.indexOf('## 二、重点复习系统学习数据'));
const focus = markdown.split('## 二、重点复习系统学习数据')[1];
for (const expected of ['函数改名', '同名资料', '| 8/10 | 15分钟 |', '| 未填写 | 未填写 |', '| 重点复习系统 |']) assert.ok(focus.includes(expected), expected);
assert.ok(!/原 Group|首次收集|复习次数|全部复习第|当前复习断点|第一次心得|另一资料心得|第二轮/.test(focus));
for (const question of state.focusReview.questions) assert.ok(!focus.includes(question.id));
for (const group of [...state.focusReview.groups, ...state.focusReview.allReviews]) assert.ok(!focus.includes(group.id));
assert.equal(JSON.stringify(state), raw); assert.equal(JSON.stringify([...app.store]), storeBefore);
const invalid = JSON.parse(raw); invalid.materials = invalid.materials.filter(material => material.id !== 'm1');
assert.doesNotMatch(app.context.PocketLearningArchive.render(JSON.stringify(invalid)).split('## 三、已熟练并移除的所有题目')[1], /第4题/);
const originalOnly = JSON.parse(raw); delete originalOnly.focusReview;
const originalMarkdown = app.context.PocketLearningArchive.render(JSON.stringify(originalOnly));
assert.equal(markdown.split('## 二、重点复习系统学习数据')[0], originalMarkdown.split('## 二、重点复习系统学习数据')[0]);
assert.equal(state.focusReview.allReviews[0].id, allId);
assert.equal(cloudCalls, 0);
console.log('PASS combined archive, unchanged original section, current source names and stable identities, complete runs/per-question metrics, empty/zero fields, statuses, all-review history, missing sources and read-only export.');
