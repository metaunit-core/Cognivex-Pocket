'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {boot,seed}=require('./helpers/pocket-learning-ui.cjs');
(async()=>{
  const key='pocket-development-v1:cognivex-pocket-state',initial=seed(2);
  const app=boot({location:new URL('http://localhost:4173/'),store:new Map([[key,JSON.stringify(initial)]])});
  const load=name=>vm.runInContext(fs.readFileSync(path.join(__dirname,'../js/'+name+'.js'),'utf8'),app.context);
  load('video-learning');load('learning-backup');
  const model=app.context.PocketVideoLearning,storage=app.context.PocketStorage;
  let state=storage.loadState();const baseline=JSON.stringify(state);
  assert.equal(model.records(state).length,0);assert.equal(JSON.stringify(state),baseline);
  const save=change=>{state=storage.updateState(state,change);};
  let first,second;
  save(next=>{first=model.create(next,{title:'课程 A',subject:'数学',url:'baidunetdisk://course',mode:'continuous'});second=model.create(next,{title:'课程 B',subject:'物理',mode:'question'});});
  assert.notEqual(first,second);assert.throws(()=>save(next=>model.create(next,{title:' ',mode:'continuous'})),/名称/);
  for(const url of ['javascript:alert(1)','data:text/html,test','java\nscript:alert(1)'])assert.throws(()=>save(next=>model.create(next,{title:'bad',mode:'continuous',url})),/不安全/);
  save(next=>model.update(next,first,'position',3));save(next=>model.update(next,first,'mode','question'));
  save(next=>model.update(next,first,'question',12));save(next=>model.update(next,first,'position',5));
  save(next=>model.update(next,first,'mode','continuous'));assert.equal(model.find(state,first).modePositions.continuous,3);
  save(next=>model.update(next,first,'mode','question'));assert.equal(model.find(state,first).modePositions.question,5);
  assert.equal(model.find(state,first).currentQuestion,12);assert.equal(model.find(state,second).currentQuestion,1);
  assert.throws(()=>save(next=>model.update(next,first,'question',0)),/题号/);
  assert.throws(()=>save(next=>model.update(next,first,'question',1.5)),/题号/);
  const bytes=app.store.get(key);app.fail.enabled=true;assert.throws(()=>save(next=>model.update(next,first,'position',6)));app.fail.enabled=false;assert.equal(app.store.get(key),bytes);
  const stale=JSON.parse(bytes);save(next=>model.update(next,second,'question',2));
  assert.throws(()=>storage.updateState(stale,next=>model.update(next,first,'question',99)),/其他窗口/);
  state=storage.loadState();assert.equal(model.find(state,first).currentQuestion,12);
  assert.throws(()=>model.groupingHandoff(state,first),/先手动/);
  save(next=>model.update(next,first,'complete'));const completed=JSON.stringify(model.find(state,first));
  save(next=>model.update(next,first,'complete'));assert.equal(JSON.stringify(model.find(state,first)),completed);
  assert.equal(model.groupingHandoff(state,first).status,'not-connected');
  save(next=>model.update(next,first,'metadata',{title:'新名称',subject:'数学',url:'https://example.test/lesson'}));
  const onlyVideo=JSON.parse(JSON.stringify(state));delete onlyVideo.videoLearning;assert.equal(JSON.stringify(onlyVideo),baseline);
  const legacyRecords=JSON.stringify(state.videoLearning.records);
  save(next=>model.saveProgress(next,'continuous','step',4));
  save(next=>model.saveProgress(next,'question','step',5));
  save(next=>model.saveProgress(next,'question','question',23));
  assert.deepEqual(JSON.parse(JSON.stringify(model.progress(state))),{intro:0,continuous:4,question:5,currentQuestion:23});
  assert.equal(JSON.stringify(state.videoLearning.records),legacyRecords);
  assert.throws(()=>save(next=>model.saveProgress(next,'question','question',0)),/题号/);
  assert.throws(()=>save(next=>model.saveProgress(next,'question','step',7)),/步骤/);
  const legacyGuidance=JSON.parse(JSON.stringify(state));
  delete legacyGuidance.videoLearning.guidance.questionStepVersion;
  legacyGuidance.videoLearning.guidance.question=4;
  const legacyBytes=JSON.stringify(legacyGuidance);
  assert.equal(model.progress(legacyGuidance).question,4);
  assert.equal(JSON.stringify(legacyGuidance),legacyBytes);
  model.saveProgress(legacyGuidance,'continuous','step',2);
  assert.equal(model.progress(legacyGuidance).question,4);
  legacyGuidance.videoLearning.guidance.questionStepVersion=2;
  legacyGuidance.videoLearning.guidance.question=7;
  assert.equal(model.progress(legacyGuidance).question,6);
  model.saveProgress(legacyGuidance,'question','step',6);
  assert.equal(model.progress(JSON.parse(JSON.stringify(legacyGuidance))).question,6);
  assert.equal(model.progress(legacyGuidance).currentQuestion,23);
  const priorGuidance=JSON.stringify(state.videoLearning.guidance),priorRecords=JSON.stringify(state.videoLearning.records);
  assert.equal(model.progress(state).intro,0);
  assert.equal(JSON.stringify(state.videoLearning.guidance),priorGuidance);
  save(next=>model.saveProgress(next,'intro','step',2));
  assert.equal(model.progress(state).intro,2);
  assert.equal(model.progress(state).continuous,4);
  assert.equal(model.progress(state).question,5);
  assert.equal(model.progress(state).currentQuestion,23);
  assert.equal(JSON.stringify(state.videoLearning.records),priorRecords);
  assert.throws(()=>save(next=>model.saveProgress(next,'intro','step',3)),/步骤/);
  const beforeFailedIntro=app.store.get(key);app.fail.enabled=true;
  assert.throws(()=>save(next=>model.saveProgress(next,'intro','step',1)));app.fail.enabled=false;
  assert.equal(app.store.get(key),beforeFailedIntro);
  save(next=>model.saveProgress(next,'continuous','step',0));
  assert.equal(model.progress(state).intro,2);
  assert.equal(model.progress(state).question,5);
  state=storage.loadState();assert.equal(model.progress(state).currentQuestion,23);
  const backup=await app.context.PocketLearningBackup.create();assert.equal((await app.context.PocketLearningBackup.verify(JSON.stringify(backup))).valid,true);
  assert.deepEqual(JSON.parse(backup.rawState).videoLearning,JSON.parse(JSON.stringify(state.videoLearning)));
  const captured=await app.context.PocketLearningBackup.createFromEntries(backup.entries);assert.equal(captured.rawState,backup.rawState);
  assert.equal(app.context.PocketLearningBackup.inspect(baseline).issues.length,0);
  const invalid=JSON.parse(backup.rawState);invalid.videoLearning.records[0].currentQuestion=0;
  assert.throws(()=>storage.saveState(invalid),/视频学习记录/);assert.ok(app.context.PocketLearningBackup.inspect(JSON.stringify(invalid)).issues.length);
  console.log('PASS independent video model: modes/positions/questions, isolation, failure/CAS, exact-once completion, legacy state and full JSON/cloud snapshot payload.');
})().catch(error=>{console.error(error);process.exitCode=1;});
