'use strict';
const assert=require('node:assert/strict');
const {boot,seed}=require('./helpers/pocket-learning-ui.cjs');
const location=new URL('http://localhost:4173/'),key='pocket-development-v1:cognivex-pocket-state';
const app=boot({location,focusReview:true,store:new Map([[key,JSON.stringify(seed(2))]])});
app.context.PocketLearning.showHome();
const before=app.store.get(key),dialog=app.document.getElementById('materials-dialog');
const selected=()=>app.document.getElementById('selected-review-entry');
const original=app.document.getElementById('learned-material-details');
const close=()=>app.all().find(node=>node.tag==='button'&&node.textContent==='关闭').fire('click');
const items=()=>app.document.getElementById('material-list-items').children;
const walk=node=>[node,...node.children.flatMap(walk)];
assert.equal(selected().children[0].tag,'svg');
assert.equal(selected().children[0]['aria-hidden'],'true');
assert.equal(selected().events.click[0],original.events.click[0],'both entries use the identical opening handler');
selected().fire('click');assert.equal(dialog.hidden,false);
assert.equal(items().length,2);assert.equal(app.store.get(key),before);
const labels=items().map(row=>walk(row).filter(node=>node.tag==='input').map(node=>node['data-material-id']));
const checkbox=walk(items()[0]).find(node=>node.tag==='input');checkbox.checked=true;checkbox.fire('change');
close();original.fire('click');
assert.equal(dialog.hidden,false);
assert.deepEqual(items().map(row=>walk(row).filter(node=>node.tag==='input').map(node=>node['data-material-id'])),labels);
assert.equal(walk(items()[0]).find(node=>node.tag==='input').checked,false,'both entries retain the original fresh-selection behavior');
close();
for(let index=0;index<3;index++)app.context.PocketLearning.showHome();
assert.equal(app.all().filter(node=>node.id==='selected-review-entry').length,1);
assert.equal(selected().events.click.length,1);
assert.equal(original.className.includes('daily-review-attention'),false);
assert.equal(app.store.get(key),before);
console.log('PASS shared modal handler, original/new entry parity, selection reset, one listener, unchanged learning data.');
