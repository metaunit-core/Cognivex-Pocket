'use strict';
const assert = require('node:assert/strict');
const { boot, seed } = require('./helpers/pocket-learning-ui.cjs');
const location = new URL('http://localhost:4173/'), key = 'pocket-development-v1:cognivex-pocket-state';
const clock = { now: new Date(2026, 9, 22, 9).getTime() };
const initial = seed(1), setup = boot({ location, clock, focusReview: true }), model = setup.context.PocketFocusReview;
model.add(initial, 'm1', 0, '1'); const id = model.create(initial, '数学', 1, model.available(initial, '数学').map(q => q.id));
let app = boot({ location, clock, focusReview: true, store: new Map([[key, JSON.stringify(initial)]]) });
const attention = () => app.document.getElementById('daily-reverse-review-entry').className.includes('daily-review-attention');
const focusAttention = () => app.document.getElementById('focus-review-home-button').className.includes('daily-review-attention');
const walk = node => [node, ...node.children.flatMap(walk)];
const click = label => { const node = walk(app.document.getElementById('focus-review')).find(n => n.tag === 'button' && n.textContent === label); assert.ok(node, label); node.fire('click'); };
assert.equal(attention(), true);
assert.equal(focusAttention(), true);
app.context.PocketFocusReviewUI.open({ subject: '数学', focusGroup: id }); click('复习');
assert.equal(attention(), true, 'starting focus review must not suppress a genuinely required reminder');
click('输出达标 → 下一步');
assert.equal(app.context.PocketReviewAdmission.status(app.state()).unlocked, true);
assert.equal(app.context.PocketDailyReverse.needsReview(app.state()), true, 'daily completion remains independent');
assert.equal(app.state().dailyReverseReview?.clickedDays, undefined);
assert.equal(app.state().dailyReverseReview?.round, undefined);
assert.equal(attention(), false, 'focus completion immediately refreshes the hidden home entry too');
assert.equal(focusAttention(), false);
const bytes = app.store.get(key);
for (const hour of [10, 15, 23]) {
  clock.now = new Date(2026, 9, 22, hour).getTime(); app.fire('focus'); app.fire('pageshow');
  assert.equal(attention(), false); assert.equal(app.store.get(key), bytes);
}
app = boot({ location, clock, focusReview: true, store: app.store }); assert.equal(attention(), false);
clock.now = new Date(2026, 9, 23, 0, 1).getTime(); app.fire('focus');
assert.equal(attention(), true, 'a previous-day focus completion does not unlock today');
assert.equal(focusAttention(), true);
assert.equal(app.store.get(key), bytes, 'reminder refresh never writes learning or completion records');
app.document.getElementById('daily-reverse-review-entry').fire('click');
assert.equal(attention(), true, 'a click without completion cannot suppress the reminder');
assert.equal(focusAttention(), true);
app.button('输出达标 → 下一步').fire('click');
assert.equal(attention(), false, 'actual daily completion stops both reminders');
assert.equal(focusAttention(), false);
const empty = boot({ location, clock, focusReview: true, store: new Map([[key, JSON.stringify(seed(0))]]) });
assert.equal(empty.document.getElementById('daily-reverse-review-entry').className.includes('daily-review-attention'), false);
console.log('PASS localhost daily reminder admission, immediate focus completion, no fake daily completion/click, same-day refresh/reload, next day, click suppression and empty library.');
