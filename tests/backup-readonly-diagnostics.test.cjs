'use strict';
const assert = require('node:assert/strict');
const { local, bind } = require('./helpers/pocket-cloud-fixture.cjs');
const { fenced } = require('./helpers/pocket-generation-fixture.cjs');
(async () => {
  const cloud = fenced(); cloud.rotate('diagnostic-cycle-000001');
  const d = local(cloud); await bind(d);
  const before = JSON.stringify([...d.store]), writes = cloud.stats.writes, commits = cloud.stats.commits;
  let report = await d.engine.diagnose();
  assert.equal(report.contentMatches, true); assert.equal(report.pending, false);
  assert.equal(report.sessionCommit.revision, 1);
  assert.equal(report.localRevision, report.cloudRevision);
  assert.equal(report.headPath, 'users/A/backup/head');
  assert.equal(JSON.stringify([...d.store]), before);
  assert.equal(cloud.stats.writes, writes); assert.equal(cloud.stats.commits, commits);
  const refresh = local(cloud, null, d.store); await refresh.engine.setUser({ uid: 'A' });
  report = await refresh.engine.diagnose(); assert.equal(report.sessionCommit, null);
  assert.equal(report.contentMatches, true); assert.equal(report.serverVerified, true);
  d.change(s => { s.materials[0].groups[0].keyQuestions = 'unsynced'; });
  report = await d.engine.diagnose(); assert.equal(report.pending, true);
  assert.equal(report.contentMatches, false); assert.equal(report.serverVerified, true);
  assert.equal(cloud.stats.commits, commits);
  const old = cloud.heads.get('A').snapshotId;
  await d.engine.retry(); report = await d.engine.diagnose();
  assert.equal(report.cloudRevision, 2); assert.equal(report.contentMatches, true);
  assert.ok(cloud.manifests.has('A/' + old));
  const stableBefore = JSON.stringify([...d.store]); cloud.stats.fail = true;
  await assert.rejects(d.engine.diagnose(), /Offline/);
  assert.equal(JSON.stringify([...d.store]), stableBefore); cloud.stats.fail = false;
  const chunkKey = [...cloud.chunks.keys()].find(k => k.startsWith('A/' + cloud.heads.get('A').snapshotId + '/'));
  const chunk = cloud.chunks.get(chunkKey); const original = chunk.content; chunk.content = 'damaged';
  await assert.rejects(d.engine.diagnose(), /损坏/); chunk.content = original;
  const head = cloud.adapter.head; let reads = 0;
  cloud.adapter.head = async uid => { reads++; const h = await head(uid); return reads === 2 ? { ...h, revision: h.revision + 1 } : h; };
  report = await d.engine.diagnose(); assert.equal(report.stable, false);
  assert.equal(report.pending, null); assert.equal(report.serverVerified, false);
  assert.equal(cloud.stats.commits, commits + 1);
  console.log('PASS: diagnostics write nothing, server snapshot/hash/generation/revision verification, changed local data, refresh without commit claim, preserved history, unavailable/corrupt/racing cloud never report success.');
})().catch(error => { console.error(error); process.exitCode = 1; });
