'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const { boot, seed } = require('./helpers/pocket-learning-ui.cjs');
const location = new URL('http://localhost:4173/'), key = 'pocket-development-v1:cognivex-pocket-state';
let app = boot({ location, focusReview: true });
const model = app.context.PocketFocusReview, state = seed(2);
state.materials.forEach(material => { material.subject = '数学'; material.groups[0].start = 1; material.groups[0].end = 20; });
state.materials[0].title = '函数'; state.materials[1].title = '圆锥';
for (let index = 0; index < 6; index++) model.add(state, index % 2 ? 'm2' : 'm1', 0, String(index + 1), false, 100 + index);
const plan = () => { const value = model.groupingPlan(state, '数学'); return { questionIds: value.questions.map(question => question.id), groupIds: value.groupIds }; };
const oldIds = model.regroup(state, '数学', 2, plan());
model.start(state, oldIds[0]);
for (let index = 0; index < 2; index++) model.transition(state, model.active(state).run.id, 'finish', { accuracy: '8/10', durationMinutes: '15', notes: '旧分组历史不展示' }, Date.now(), index);
const oldHistory = JSON.stringify(state.focusReview.groups[0].runs);
model.regroup(state, '数学', 3, plan(), true);
const current = state.focusReview.groups.filter(group => !group.retiredAt);
model.start(state, current[0].id);
model.transition(state, model.active(state).run.id, 'save', { accuracy: '0/2', durationMinutes: '0' });
model.setStatus(state, state.focusReview.questions[4].id, 'mastered');
model.setStatus(state, state.focusReview.questions[5].id, 'removed');
state.focusReview.questions[2].groupKey = 'id:missing';
state.materials[0].title = '函数新名';
app = boot({ location, store: new Map([[key, JSON.stringify(state)]]), focusReview: true });
vm.runInContext(fs.readFileSync(path.join(__dirname, '../js/learning-backup.js'), 'utf8'), app.context);
vm.runInContext(fs.readFileSync(path.join(__dirname, '../js/learning-archive.js'), 'utf8'), app.context);
const before = JSON.stringify([...app.store]), raw = JSON.stringify(state);
const markdown = app.context.PocketLearningArchive.render(raw), section = markdown.split('## 二、重点复习系统学习数据')[1];
assert.equal((section.match(/### 重点 Group /g) || []).length, 2);
assert.match(section, /\| 函数新名 \| 第1题 \| 未填写 \| 未填写 \|\n\| 圆锥 \| 第2题 \| — \| — \|/);
assert.doesNotMatch(section, /最新成绩记录于|完整 Group 复习/);
assert.ok(!/8\/10|15分钟|旧分组历史|首次收集|复习次数|保存分组顺序|当前复习断点|原 Group/.test(section));
const removals = markdown.split('## 三、已熟练并移除的所有题目')[1];
assert.doesNotMatch(removals, /第3题|来源不可用/);
assert.match(removals, /\| 第5题 \| 重点复习系统 \|/);
assert.match(removals, /\| 第6题 \| 重点复习系统 \|/);
assert.equal((removals.match(/第5题/g) || []).length, 1);
const walk = node => [node, ...node.children.flatMap(walk)];
app.context.PocketFocusReviewUI.open({ subject: '数学', questionList: true });
const page = app.document.getElementById('focus-review');
assert.ok(!walk(page).some(node => /管理题目|重新加入|已熟练、已移出/.test(node.textContent)));
const numbers = walk(page).filter(node => node.className === 'focus-strip-numbers').map(node => node.textContent).join(' ');
assert.match(numbers, /第 1 题/); assert.match(numbers, /第 2、4 题/); assert.ok(!/3|5|6/.test(numbers));
assert.equal(app.store.get(key), raw);
assert.equal(JSON.stringify(state), raw); assert.equal(JSON.stringify(state.focusReview.groups[0].runs), oldHistory);
const noFocus = JSON.parse(raw); delete noFocus.focusReview;
assert.equal(markdown.split('## 二、重点复习系统学习数据')[0], app.context.PocketLearningArchive.render(JSON.stringify(noFocus)).split('## 二、重点复习系统学习数据')[0]);
const noGroups = JSON.parse(raw); noGroups.focusReview.groups.forEach(group => { group.retiredAt = 1; });
assert.match(app.context.PocketLearningArchive.render(JSON.stringify(noGroups)), /暂无重点复习数据/);
const future = JSON.parse(raw); future.focusReview.session = null;
model.start(future, current[0].id);
assert.equal(model.active(future).run.members.length, 2, 'missing optional links must not hide valid source questions');
console.log('PASS latest-group-only concise export, real current names, independent current/old scores, missing/zero metrics, hidden source/status archive, no management UI, invalid-source filtering and read-only original history.');
