'use strict';
const assert = require('node:assert/strict');
const { boot, seed } = require('./helpers/pocket-learning-ui.cjs');
const key = 'pocket-development-v1:cognivex-pocket-state';
const location = new URL('http://localhost:4173/');
let app = boot({ location, focusReview: true });
const model = app.context.PocketFocusReview, history = app.context.PocketHistory;
const state = seed(1); delete state.materials[0].groups[0].id;
state.materials[0].status = 'learning'; state.materials[0].groups[0].start = 1; state.materials[0].groups[0].end = 20;
model.add(state, 'm1', 0, '3、7、12');
const legacyKey = state.focusReview.questions[0].groupKey;
assert.match(legacyKey, /^legacy:/); assert.equal(model.available(state, '数学').length, 3);
state.materials[0].status = 'completed'; history.initialize(state);
assert.ok(state.materials[0].groups[0].id, 'the real original history admission assigns an ID after learning');
const originalAfterAdmission = JSON.stringify(state.materials);
assert.equal(model.available(state, '数学').length, 3, 'history admission must not invalidate already collected legacy sources');
const beforeRead = JSON.stringify(state); model.available(state, '数学'); assert.equal(JSON.stringify(state), beforeRead);
const first = model.create(state, '数学', 1, model.available(state, '数学').slice(0, 1).map(question => question.id));
assert.equal(model.available(state, '数学').length, 2);
const second = model.create(state, '数学', 2, model.available(state, '数学').map(question => question.id));
assert.equal(model.available(state, '数学').length, 0);
const existingGroups = JSON.stringify(state.focusReview.groups);
assert.equal(model.add(state, 'm1', 0, '3').duplicates, 1);
assert.equal(state.focusReview.questions.length, 3, 'a legacy source gaining an ID must not create a duplicate identity');
model.add(state, 'm1', 0, '15、18'); assert.equal(model.available(state, '数学').length, 2);
assert.equal(JSON.stringify(state.focusReview.groups), existingGroups);
assert.equal(JSON.stringify(state.materials), originalAfterAdmission);
assert.equal(state.focusReview.questions[0].groupKey, legacyKey, 'do not migrate original question or historical group keys');
app = boot({ store: new Map([[key, JSON.stringify(state)]]), location, focusReview: true });
assert.equal(app.context.PocketFocusReview.available(app.state(), '数学').length, 2);
app.context.PocketFocusReviewUI.open({ subject: '数学' });
const walk = node => [node, ...node.children.flatMap(walk)];
let page = app.document.getElementById('focus-review');
assert.ok(walk(page).some(node => node.textContent === '每组题数'));
const beforeFail = app.store.get(key); app.fail.enabled = true;
app.document.getElementById('focus-group-size').value = '1';
walk(page).find(node => node.tag === 'button' && node.textContent === '分组').fire('click');
walk(page).find(node => node.tag === 'button' && node.textContent === '确认').fire('click');
assert.equal(app.store.get(key), beforeFail); app.fail.enabled = false;
assert.equal(app.context.PocketFocusReview.available(app.state(), '数学').length, 2);
const isolated = JSON.parse(JSON.stringify(state)), available = model.available(isolated, '数学');
model.setStatus(isolated, available[0].id, 'mastered'); model.setStatus(isolated, available[1].id, 'removed');
assert.equal(model.available(isolated, '数学').length, 0);
model.add(isolated, 'm1', 0, '15、18'); assert.equal(model.available(isolated, '数学').length, 2, 'explicit collection restores training without duplicate records');
model.setStatus(isolated, available[0].id, 'active'); assert.equal(model.available(isolated, '数学').length, 2);
const removedGroup = JSON.parse(JSON.stringify(state)); removedGroup.focusReview.groups = removedGroup.focusReview.groups.filter(group => group.id !== second);
assert.equal(model.available(removedGroup, '数学').length, 4);
removedGroup.focusReview.questions.forEach(question => { question.focusGroupId = 'deleted-old-group'; });
assert.equal(model.available(removedGroup, '数学').length, 4, 'stale assignment hints cannot replace real group membership');
const running = JSON.parse(JSON.stringify(state)); model.start(running, first);
const activeBytes = JSON.stringify(running.focusReview.groups[0].runs);
running.focusReview.groups[0].retiredAt = 1;
assert.equal(model.available(running, '数学').length, 2, 'even an inconsistent retired marker cannot release a running group');
assert.equal(JSON.stringify(running.focusReview.groups[0].runs), activeBytes);
const changed = JSON.parse(JSON.stringify(state)); changed.materials[0].groups[0].start = 2;
assert.equal(model.locate(changed, changed.focusReview.questions[0]), null, 'do not guess legacy source identity when range changes');
console.log('PASS pending 3/2/0 then 2, actual history ID assignment compatibility, same-source deduplication, read-only old-key resolution, reload, mastery/removal/rejoin, deleted/stale groups, active-run reservation and failed save preservation.');
