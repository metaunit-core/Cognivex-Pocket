'use strict';
const assert = require('node:assert/strict');
const { boot, seed } = require('./helpers/pocket-learning-ui.cjs');
const key = 'pocket-development-v1:cognivex-pocket-state', location = new URL('http://localhost:4173/');
const state = seed(2);
state.materials.forEach(material => { material.subject = '数学'; material.groups[0].start = 1; material.groups[0].end = 30; });
state.materials[0].title = '函数'; state.materials[1].title = '几何';
let app = boot({ store: new Map([[key, JSON.stringify(state)]]), location, focusReview: true });
const model = app.context.PocketFocusReview;
for (const [material, number, at] of [['m1', 6, 600], ['m2', 1, 100], ['m1', 5, 500], ['m2', 2, 200], ['m1', 4, 400], ['m2', 3, 300]]) model.add(state, material, 0, String(number), false, at);
for (const size of [1, 2, 1, 2]) model.create(state, '数学', size, model.available(state, '数学').slice(0, size).map(question => question.id));
model.add(state, 'm1', 0, '20', false, 700);
const originalGroups = JSON.stringify(state.focusReview.groups), originalMaterials = JSON.stringify(state.materials);
const selected = model.allQuestions(state, '数学');
assert.equal(selected.length, 6);
assert.deepEqual(JSON.parse(JSON.stringify(selected.map(question => question.number))), [1, 2, 3, 4, 5, 6]);
const duplicate = JSON.parse(JSON.stringify(state)); duplicate.focusReview.groups[1].members.push(duplicate.focusReview.groups[0].members[0]);
assert.equal(model.allQuestions(duplicate, '数学').length, 6);
model.setStatus(duplicate, selected[0].id, 'mastered'); model.setStatus(duplicate, selected[1].id, 'removed');
assert.equal(model.allQuestions(duplicate, '数学').length, 4);
const legacy = JSON.parse(JSON.stringify(state)); legacy.focusReview.questions.forEach(question => { delete question.addedAt; });
assert.equal(JSON.stringify(model.allQuestions(legacy, '数学').map(question => question.id)), JSON.stringify(legacy.focusReview.questions.slice(0, 6).map(question => question.id)));
app = boot({ store: new Map([[key, JSON.stringify(state)]]), location, focusReview: true });
const walk = node => [node, ...node.children.flatMap(walk)];
const page = () => app.document.getElementById('focus-review');
const text = () => walk(page()).map(node => node.textContent).join('\n');
const click = label => { const node = walk(page()).find(node => node.tag === 'button' && node.textContent === label && !node.disabled); assert.ok(node, label); node.fire('click'); };
app.context.PocketFocusReviewUI.open({ subject: '数学' });
const actions = walk(page()).find(node => node.className === 'focus-group-actions');
assert.deepEqual(actions.children.map(node => node.textContent), ['分组', '全部复习']);
const beforeFail = app.store.get(key); app.fail.enabled = true; click('全部复习');
assert.equal(app.store.get(key), beforeFail); app.fail.enabled = false; click('全部复习');
assert.match(text(), /全部重点题 · 第 1\/6 题/); assert.match(text(), /数学 · 几何/);
const allId = app.state().focusReview.session.groupId;
assert.equal(app.state().focusReview.groups.length, 4);
assert.equal(app.context.PocketReviewAdmission.status(app.state()).focusCompleted, false);
assert.equal(app.state().reviewAdmission.lastClicked.system, 'focus');
const oldNext = walk(page()).find(node => node.textContent === '输出达标 → 下一步');
click('输出达标 → 下一步'); oldNext.fire('click');
assert.equal(app.state().focusReview.allReviews[0].runs[0].completedCount, 1);
app = boot({ store: app.store, location, focusReview: true });
app.context.PocketFocusReviewUI.open({ subject: '数学', focusGroup: allId });
assert.match(text(), /第 2\/6 题/);
const snapshot = app.state();
app.context.PocketFocusReview.add(snapshot, 'm1', 0, '21', false, 800);
app.store.set(key, JSON.stringify(snapshot));
app = boot({ store: app.store, location, focusReview: true });
app.context.PocketFocusReviewUI.open({ subject: '数学', focusGroup: allId });
assert.equal(app.state().focusReview.allReviews[0].members.length, 6);
for (let index = 1; index < 5; index++) {
  click('输出达标 → 下一步');
  assert.equal(app.context.PocketReviewAdmission.status(app.state()).focusCompleted, false);
}
assert.match(text(), /数学 · 函数/); assert.match(text(), /第 6\/6 题/);
const beforeFinal = app.store.get(key); app.fail.enabled = true; click('输出达标 → 下一步');
assert.equal(app.store.get(key), beforeFinal); app.fail.enabled = false; click('输出达标 → 下一步');
assert.match(text(), /全部重点题复习完成/);
assert.equal(app.state().focusReview.session, null);
assert.equal(app.context.PocketReviewAdmission.status(app.state()).focusCompleted, true);
const run = app.state().focusReview.allReviews[0].runs[0];
assert.equal(run.completedCount, 6); assert.ok(Number.isFinite(run.completedAt));
assert.equal(JSON.stringify(app.state().focusReview.groups.map(group => ({ ...group, runs: [] }))), originalGroups);
assert.ok(app.state().focusReview.groups.every(group => group.runs.length === 1 && group.runs[0].sourceAllRunId === run.id));
assert.equal(JSON.stringify(app.state().materials), originalMaterials);
const reopened = boot({ store: app.store, location, focusReview: true });
assert.equal(reopened.state().focusReview.allReviews[0].runs[0].completedCount, 6);
const frozenState = JSON.parse(JSON.stringify(state));
const frozenId = model.startAll(frozenState, '数学');
const frozenQueue = JSON.stringify(model.active(frozenState).run.members);
const frozenRun = JSON.stringify(model.active(frozenState).run);
const frozenPlan = model.groupingPlan(frozenState, '数学');
assert.throws(() => model.regroup(frozenState, '数学', 2, { questionIds: frozenPlan.questions.map(question => question.id), groupIds: frozenPlan.groupIds }, true), /未完成/);
assert.equal(JSON.stringify(model.active(frozenState).run), frozenRun);
assert.equal(JSON.stringify(model.active(frozenState).run.members), frozenQueue);
assert.equal(model.startAll(frozenState, '数学'), frozenId);
console.log('PASS all-review saved-time queue, four groups/six questions, dedup/status exclusion, shared continuous UI, stale clicks, resume, immutable queue, failed saves, independent history and final-only admission.');
(async () => {
  const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
  vm.runInContext(fs.readFileSync(path.join(__dirname, '../js/learning-backup.js'), 'utf8'), app.context);
  const backup = await app.context.PocketLearningBackup.create();
  assert.equal((await app.context.PocketLearningBackup.verify(JSON.stringify(backup))).valid, true);
  const imported = JSON.parse(backup.rawState);
  assert.equal(JSON.stringify(imported.focusReview.allReviews), JSON.stringify(app.state().focusReview.allReviews));
  assert.equal(JSON.stringify(model.root(imported).groups), JSON.stringify(app.state().focusReview.groups));
})().catch(error => { console.error(error); process.exitCode = 1; });
