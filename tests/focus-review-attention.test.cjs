'use strict';
const assert = require('node:assert/strict');
const { boot, seed } = require('./helpers/pocket-learning-ui.cjs');
const location = new URL('http://localhost:4173/'), key = 'pocket-development-v1:cognivex-pocket-state';
const clock = { now: new Date(2026, 9, 21, 9).getTime() };
let app = boot({ location, clock, store: new Map([[key, JSON.stringify(seed(1))]]), focusReview: true });
const attention = id => app.document.getElementById(id).className.includes('daily-review-attention');
assert.equal(attention('focus-review-home-button'), true);
assert.equal(attention('daily-reverse-review-entry'), true);
const original = JSON.stringify(app.state().materials);
app.document.getElementById('focus-review-home-button').fire('click');
assert.equal(attention('focus-review-home-button'), false);
assert.equal(app.context.PocketReviewAdmission.status(app.state()).unlocked, false);
assert.equal(JSON.stringify(app.state().materials), original);
assert.equal(app.state().dailyReverseReview, undefined);
app.context.PocketLearning.showHome();
assert.equal(attention('daily-reverse-review-entry'), true);
assert.equal(attention('focus-review-home-button'), false);
app.document.getElementById('daily-reverse-review-entry').fire('click');
app.context.PocketLearning.showHome();
assert.equal(attention('focus-review-home-button'), false);
app = boot({ location, clock, store: app.store, focusReview: true });
app.context.PocketLearning.showHome(); assert.equal(attention('focus-review-home-button'), false);
clock.now = new Date(2026, 9, 22, 9).getTime(); app.fire('focus');
assert.equal(attention('focus-review-home-button'), true);
const empty = boot({ location, clock, focusReview: true });
assert.equal(empty.document.getElementById('focus-review-home-button').className.includes('daily-review-attention'), false);
console.log('PASS shared animation style, independent durable focus click suppression, next-day refresh, no fake completion and original daily behavior.');
